def _add_top_legend(fig, axes):
    try:
        flat_axes = np.ravel(axes)
    except Exception:
        flat_axes = [axes]
    handles = []
    labels = []
    for ax in flat_axes:
        try:
            h, l = ax.get_legend_handles_labels()
        except Exception:
            continue
        for hh, ll in zip(h, l):
            if ll and ll not in labels:
                handles.append(hh)
                labels.append(ll)
    if not handles:
        return None
    return fig.legend(handles, labels, loc="upper center", bbox_to_anchor=(0.5, 0.995),
                      ncol=min(max(len(labels), 1), 4), frameon=False,
                      fontsize=14.5, handlelength=1.8, columnspacing=1.1)


def parse_edges(edge_string: str) -> np.ndarray:
    edges = np.array([float(x) for x in str(edge_string).replace(";", ",").split(",") if str(x).strip()], dtype=float)
    if len(edges) < 2 or not np.all(np.diff(edges) > 0):
        raise ValueError(f"Invalid z-bin edges: {edge_string}")
    return edges


def unit_xyz_from_radec(ra_deg: np.ndarray, dec_deg: np.ndarray) -> np.ndarray:
    ra = np.deg2rad(np.asarray(ra_deg, dtype=float))
    dec = np.deg2rad(np.asarray(dec_deg, dtype=float))
    c = np.cos(dec)
    return np.column_stack([c * np.cos(ra), c * np.sin(ra), np.sin(dec)]).astype(np.float64)


def radec_from_unit_xyz(vec: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    v = np.asarray(vec, dtype=float)
    if v.ndim == 1:
        v = v[None, :]
    v = v / np.linalg.norm(v, axis=1, keepdims=True)
    ra = (np.rad2deg(np.arctan2(v[:, 1], v[:, 0])) + 360.0) % 360.0
    dec = np.rad2deg(np.arcsin(np.clip(v[:, 2], -1.0, 1.0)))
    return ra, dec


def healpix_direction_grid(nside: int) -> pd.DataFrame:
    require_healpy()
    npix = hp.nside2npix(int(nside))
    pix = np.arange(npix, dtype=int)
    theta, phi = hp.pix2ang(int(nside), pix, nest=False)
    dec = 90.0 - np.rad2deg(theta)
    ra = np.rad2deg(phi) % 360.0
    xyz = unit_xyz_from_radec(ra, dec)
    keep = dec >= -1e-12  # northern equatorial hemisphere only
    return pd.DataFrame({
        "pix": pix[keep],
        "ra_deg": ra[keep],
        "dec_deg": dec[keep],
        "x": xyz[keep, 0],
        "y": xyz[keep, 1],
        "z": xyz[keep, 2],
    }).reset_index(drop=True)


def read_arm_table(path: Path) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError(path)
    d = pd.read_csv(path)
    from spirality.selection import attach_parent_metadata, SCHEMA_VERSION
    parent_path = path.parent / "node_spirality.csv"
    if parent_path.exists():
        d = attach_parent_metadata(d, pd.read_csv(parent_path), accepted_only=True)
    elif {"parent_status", "parent_n_arms_valid", "analysis_schema"}.issubset(d):
        if not d.analysis_schema.astype(str).eq(SCHEMA_VERSION).all():
            raise ValueError("Arm analysis schema is stale; rerun v88 selection")
        d = d.loc[d.parent_status.eq("ok") & d.parent_n_arms_valid.ge(2)].copy()
    else:
        raise ValueError("Extrinsic inference requires the parent table or verified v88 accepted-FANS metadata")
    if "S_tangential" not in d.columns:
        if "mean_t_phi" in d.columns:
            d["S_tangential"] = pd.to_numeric(d["mean_t_phi"], errors="coerce")
        else:
            raise ValueError(f"{path} has no S_tangential or mean_t_phi column")
    if "ra" not in d.columns or "dec" not in d.columns:
        raise ValueError(f"{path} must contain ra and dec columns")
    if "z_mid" in d.columns:
        z = pd.to_numeric(d["z_mid"], errors="coerce")
    elif "z_center" in d.columns:
        z = pd.to_numeric(d["z_center"], errors="coerce")
    elif "z_low" in d.columns:
        z = pd.to_numeric(d["z_low"], errors="coerce")
    else:
        z = pd.Series(np.nan, index=d.index)
    if "z_low" in d.columns:
        zlow = pd.to_numeric(d["z_low"], errors="coerce")
        z = np.where(np.isfinite(z.to_numpy(float)), z.to_numpy(float), zlow.to_numpy(float))
    d["z_eff"] = z
    keep = (
        np.isfinite(pd.to_numeric(d["ra"], errors="coerce"))
        & np.isfinite(pd.to_numeric(d["dec"], errors="coerce"))
        & np.isfinite(pd.to_numeric(d["S_tangential"], errors="coerce"))
        & np.isfinite(pd.to_numeric(d["z_eff"], errors="coerce"))
    )
    if not np.all(keep):
        raise ValueError("Nonfinite accepted arm data; refusing to change a FANS multiplicity during inference")
    d = d.loc[keep].copy().reset_index(drop=True)
    d["ra"] = pd.to_numeric(d["ra"], errors="coerce").astype(float)
    d["dec"] = pd.to_numeric(d["dec"], errors="coerce").astype(float)
    d["S_tangential"] = pd.to_numeric(d["S_tangential"], errors="coerce").astype(float)
    d["z_eff"] = pd.to_numeric(d["z_eff"], errors="coerce").astype(float)
    return d



def arm_weights(d: pd.DataFrame, mode: str) -> np.ndarray:
    mode = str(mode).lower()
    n = len(d)
    if mode == "uniform":
        return np.ones(n, dtype=np.float64)
    if mode == "n_segments":
        col = "n_arm_segments_total" if "n_arm_segments_total" in d.columns else "n_segments_valid"
        if col not in d.columns:
            col = "n_arm_segments_valid" if "n_arm_segments_valid" in d.columns else col
        vals = pd.to_numeric(d[col], errors="coerce").to_numpy(float) if col in d.columns else np.ones(n, dtype=float)
        return np.where(np.isfinite(vals) & (vals > 0), vals, 0.0).astype(np.float64)
    if mode == "mean_density":
        if "mean_segment_density" in d.columns:
            w = pd.to_numeric(d["mean_segment_density"], errors="coerce").to_numpy(float)
        elif "mean_arm_density" in d.columns:
            w = pd.to_numeric(d["mean_arm_density"], errors="coerce").to_numpy(float)
        else:
            w = np.ones(n, dtype=float)
        return np.where(np.isfinite(w) & (w > 0), w, 0.0).astype(np.float64)
    if mode == "sqrt_mean_density":
        w = arm_weights(d, "mean_density")
        return np.sqrt(np.maximum(w, 0.0)).astype(np.float64)
    if mode == "sqrt_points":
        col = "n_points_used_total" if "n_points_used_total" in d.columns else "n_points_total"
        vals = pd.to_numeric(d[col], errors="coerce").to_numpy(float) if col in d.columns else np.ones(n, dtype=float)
        return np.sqrt(np.maximum(np.where(np.isfinite(vals), vals, 0.0), 0.0)).astype(np.float64)
    raise ValueError(f"Unsupported weight mode: {mode}")



def weighted_dipole_fit_with_intercept(mu: np.ndarray, h: np.ndarray, w: np.ndarray) -> tuple[float, float, float, float, int]:
    """Weighted fit h = H0 + A*mu for one trial axis.

    Returns (A, H0, denom, mu_bar, n_valid).  The denominator is
    sum_i w_i (mu_i - <mu>_w)^2.  Fitting the intercept removes leakage of an
    isotropic projected handedness component into the dipole when the footprint
    is incomplete.
    """
    mu = np.asarray(mu, dtype=float)
    h = np.asarray(h, dtype=float)
    w = np.asarray(w, dtype=float)
    ok = np.isfinite(mu) & np.isfinite(h) & np.isfinite(w) & (w > 0)
    n_ok = int(np.count_nonzero(ok))
    if n_ok < 2:
        return np.nan, np.nan, np.nan, np.nan, n_ok
    ww = w[ok]
    mm = mu[ok]
    yy = h[ok]
    sw = float(np.sum(ww))
    if sw <= 0:
        return np.nan, np.nan, np.nan, np.nan, n_ok
    mu_bar = float(np.sum(ww * mm) / sw)
    h_bar = float(np.sum(ww * yy) / sw)
    xc = mm - mu_bar
    den = float(np.sum(ww * xc * xc))
    if den <= 0:
        return np.nan, h_bar, den, mu_bar, n_ok
    A = float(np.sum(ww * xc * yy) / den)
    H0 = float(h_bar - A * mu_bar)
    return A, H0, den, mu_bar, n_ok



def _dipole_fit_many_with_intercept(mu: np.ndarray, h: np.ndarray, weights: np.ndarray) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """Vectorized weighted fits h = H0 + A*mu for many trial axes.

    Parameters
    ----------
    mu : array, shape (n_arms, n_directions)
        Direction cosine n_i.d for each arm and trial axis.
    h, weights : arrays, shape (n_arms,)
        Arm handedness and catalogue weights.

    Returns
    -------
    A, H0, den, mu_bar : arrays, shape (n_directions,)
    """
    mu = np.asarray(mu, dtype=np.float64)
    h = np.asarray(h, dtype=np.float64)
    weights = np.asarray(weights, dtype=np.float64)
    sw = float(np.sum(weights))
    if sw <= 0:
        m = mu.shape[1]
        return (np.full(m, np.nan), np.full(m, np.nan), np.full(m, np.nan), np.full(m, np.nan))
    sy = float(np.sum(weights * h))
    h_bar = sy / sw
    smu = np.sum(weights[:, None] * mu, axis=0)
    smm = np.sum(weights[:, None] * mu * mu, axis=0)
    smy = np.sum(weights[:, None] * mu * h[:, None], axis=0)
    mu_bar = smu / sw
    den = smm - (smu * smu) / sw
    num = smy - smu * sy / sw
    A = np.where(den > 0, num / den, np.nan)
    H0 = h_bar - A * mu_bar
    return A, H0, den, mu_bar



def _dipole_slope_signflip_noise_for_axis(mu: np.ndarray, h: np.ndarray, w: np.ndarray) -> float:
    """Analytic independent sign-flip scale for the slope with an intercept."""
    A, H0, den, mu_bar, n_ok = weighted_dipole_fit_with_intercept(mu, h, w)
    if not np.isfinite(den) or den <= 0:
        return np.nan
    ok = np.isfinite(mu) & np.isfinite(h) & np.isfinite(w) & (w > 0)
    xc = mu[ok] - mu_bar
    return float(np.sqrt(np.sum((w[ok] * xc * h[ok]) ** 2)) / den)



def scan_axis_grid(
    *, arm_xyz: np.ndarray, sphi: np.ndarray, directions: pd.DataFrame,
    weights: Optional[np.ndarray] = None, chunk_size: int = 128,
    progress: bool = True, count_weights: Optional[np.ndarray] = None,
) -> pd.DataFrame:
    """Scan the continuous dipole with an intercept; retain both sign diagnostics.

    Primary: sign(h*mu), exactly Equation (6). Secondary: sign((h-H0)*mu).
    count_weights is a bootstrap replication count, NEVER the scientific W_i.
    """
    sphi, arm_xyz = np.asarray(sphi,float), np.asarray(arm_xyz,float)
    weights = np.ones(len(sphi)) if weights is None else np.asarray(weights,float)
    cw = np.ones(len(sphi)) if count_weights is None else np.asarray(count_weights,float)
    valid=np.isfinite(sphi)&np.isfinite(weights)&(weights>0)&np.isfinite(cw)&(cw>0)&np.all(np.isfinite(arm_xyz),axis=1)
    h,w,xyz,cw=sphi[valid],weights[valid],arm_xyz[valid],cw[valid]
    if len(h)<2 or not len(directions): raise ValueError("Insufficient arms/directions for an extrinsic scan")
    dirs=directions[["x","y","z"]].to_numpy(float); rows=[]
    for i0 in range(0,len(dirs),int(chunk_size)):
        i1=min(i0+int(chunk_size),len(dirs))
        if progress: print(f"[dipole-scan] directions {i0+1}-{i1}/{len(dirs)}",flush=True)
        mu=xyz@dirs[i0:i1].T
        A,H0,den,mu_bar=_dipole_fit_many_with_intercept(mu,h,w)
        sub=directions.iloc[i0:i1].copy()
        sub["A_dip"]=A; sub["A_dip_abs"]=np.abs(A); sub["H0_dip"]=H0
        sub["mu_bar"]=mu_bar; sub["dipole_design_den"]=den
        sub["H_ext"]=A; sub["H_ext_abs"]=np.abs(A); sub["H0_ext"]=H0
        for suffix,arg in [("",mu*h[:,None]),("_residual",mu*(h[:,None]-H0[None,:]))]:
            pos=np.sum((arg>0)*cw[:,None],axis=0); neg=np.sum((arg<0)*cw[:,None],axis=0)
            tot=pos+neg
            asym=np.divide(pos-neg,tot,out=np.full(len(tot),np.nan),where=tot>0)
            sub[f"sign_asym_ext{suffix}"]=asym
            sub[f"sign_asym_ext{suffix}_percent"]=100*asym
            sub[f"n_sign_ext{suffix}"]=tot
        arg=mu*h[:,None]
        pw=np.sum((arg>0)*w[:,None],axis=0); nw=np.sum((arg<0)*w[:,None],axis=0)
        aw=np.divide(pw-nw,pw+nw,out=np.full(len(pw),np.nan),where=(pw+nw)>0)
        sub["sign_asym_ext_weighted"]=aw; sub["sign_asym_ext_weighted_percent"]=100*aw
        sub["axial_sign_definition"]="raw_sign_h_mu"
        rows.append(sub)
    return pd.concat(rows,ignore_index=True).sort_values("A_dip_abs",ascending=False).reset_index(drop=True)


def best_axis_from_scan(scan: pd.DataFrame, *, objective: str = "dipole") -> dict:
    """Select an AXIS using |A|; report signed values on its positive-Dec representative.

    A_dip_abs is the optimization/test statistic. A_dip/H_ext remain signed.
    The hemisphere convention never depends on the measured handedness sign.
    """
    if len(scan)==0: raise ValueError("Empty scan")
    if objective not in {"dipole","axial_sign"}: raise ValueError(f"Unknown axis objective {objective}")
    col="A_dip_abs" if objective=="dipole" else "sign_asym_ext_percent"
    vals=np.abs(pd.to_numeric(scan[col],errors="coerce").to_numpy(float))
    if not np.isfinite(vals).any(): raise ValueError("No finite scan objectives")
    row=scan.iloc[int(np.nanargmax(vals))]
    ra,dec=float(row.ra_deg)%360,float(row.dec_deg)
    flip=-1. if dec<0 or (dec==0 and ra>=180) else 1.
    if flip<0: ra,dec=_antipode_radec(ra,dec)
    signed=flip*float(row.A_dip); asym=flip*float(row.sign_asym_ext)
    resid=flip*float(row.get("sign_asym_ext_residual",np.nan))
    return {"pix":int(row["pix"]),"ra_deg":ra,"dec_deg":dec,
            "ra_deg_raw":float(row.ra_deg),"dec_deg_raw":float(row.dec_deg),
            "A_dip":signed,"A_dip_signed_axis":signed,"A_dip_raw":float(row.A_dip),"A_dip_abs":abs(signed),
            "H_ext":signed,"H_ext_signed_axis":signed,"H_ext_raw":float(row.A_dip),"H_ext_abs":abs(signed),
            "H0_dip":float(row.H0_dip),"H0_ext":float(row.H0_dip),
            "mu_bar":flip*float(row.mu_bar),"mu_bar_raw":float(row.mu_bar),
            "dipole_design_den":float(row.dipole_design_den),"sign_flip":1.,"raw_sign_flip":flip,
            "sign_asym_ext":asym,"sign_asym_ext_percent":100*asym,
            "sign_asym_ext_residual":resid,"sign_asym_ext_residual_percent":100*resid,
            "axis_objective":objective,"axis_objective_value":float(vals[np.nanargmax(vals)]),
            "axis_representative":"positive_dec","axial_sign_definition":"raw_sign_h_mu",
            "extrinsic_template":"dipole_with_intercept;raw_axial_sign;residual_control",
            "analysis_schema":"88.1"}


def extrinsic_values_for_axis(d: pd.DataFrame, axis: dict) -> np.ndarray:
    """Return residual diagnostic mu*(h-H0); NOT the primary raw axial-sign statistic."""
    xyz = unit_xyz_from_radec(d["ra"].to_numpy(float), d["dec"].to_numpy(float))
    avec = unit_xyz_from_radec(np.array([axis["ra_deg"]]), np.array([axis["dec_deg"]]))[0]
    mu = xyz @ avec
    h0 = float(axis.get("H0_dip", axis.get("H0_ext", 0.0)))
    if not np.isfinite(h0):
        h0 = 0.0
    return mu * (d["S_tangential"].to_numpy(float) - h0)



def _dipole_fit_for_axis(xyz: np.ndarray, h: np.ndarray, w: np.ndarray, avec: np.ndarray) -> tuple[float, float]:
    """Return (A_dip, H0) for one fixed axis with an intercept."""
    mu = xyz @ avec
    A, H0, den, mu_bar, n_ok = weighted_dipole_fit_with_intercept(mu, h, w)
    return A, H0



def _dipole_amplitude_for_axis(xyz: np.ndarray, h: np.ndarray, w: np.ndarray, avec: np.ndarray) -> float:
    A, H0 = _dipole_fit_for_axis(xyz, h, w, avec)
    return A


def _axis_vector_from_best(axis: dict) -> np.ndarray:
    return unit_xyz_from_radec(np.array([axis["ra_deg"]]), np.array([axis["dec_deg"]]))[0]


def _stats_for_fixed_axis_subset(xyz: np.ndarray, h: np.ndarray, w: np.ndarray, axis: dict,
                                 count_weights: Optional[np.ndarray] = None) -> dict:
    """Signed fixed-axis statistics. Error columns are filled ONLY by spatial bootstrap."""
    xyz,h,w=np.asarray(xyz,float),np.asarray(h,float),np.asarray(w,float)
    cw=np.ones(len(h)) if count_weights is None else np.asarray(count_weights,float)
    valid=np.isfinite(h)&np.isfinite(w)&(w>0)&np.isfinite(cw)&(cw>0)&np.all(np.isfinite(xyz),axis=1)
    xyz,h,w,cw=xyz[valid],h[valid],w[valid],cw[valid]
    mu=xyz@_axis_vector_from_best(axis)
    A,H0,den,mu_bar,n_ok=weighted_dipole_fit_with_intercept(mu,h,w)
    diagnostic_noise=_dipole_slope_signflip_noise_for_axis(mu,h,w)
    angle=float(np.rad2deg(np.arcsin(A))) if np.isfinite(A) and abs(A)<=1 else np.nan
    out={"A_dip":A,"A_dip_signed_axis":A,"A_dip_abs":abs(A),"A_dip_err":np.nan,
         "H0_dip":H0,"H_ext":A,"H_ext_signed_axis":A,"H_ext_abs":abs(A),"H0_ext":H0,"H_ext_err":np.nan,
         "A_dip_angle_deg":angle,"H_ext_angle_deg":angle,"H_ext_angle_err_deg":np.nan,
         "A_dip_independent_signflip_noise_diagnostic":diagnostic_noise,
         "dipole_design_den":den,"mu_bar":mu_bar,"n_arms_fit":n_ok,
         "axial_sign_definition":"raw_sign_h_mu","error_model":"pending_spatial_bootstrap"}
    for suffix,arg in [("",mu*h),("_residual",mu*(h-H0))]:
        plus=float(cw[arg>0].sum()); minus=float(cw[arg<0].sum()); total=plus+minus
        asym=(plus-minus)/total if total>0 else np.nan
        out.update({f"sign_asym_ext{suffix}":asym,f"sign_asym_ext{suffix}_percent":100*asym,
                    f"sign_asym_ext{suffix}_percent_err":np.nan,
                    f"n_plus_ext{suffix}":plus,f"n_minus_ext{suffix}":minus,f"n_sign_ext{suffix}":total})
    out["sign_noise_percent"]=100/np.sqrt(out["n_sign_ext"]) if out["n_sign_ext"]>0 else np.nan
    return out


def bin_extrinsic_stats(
    d: pd.DataFrame,
    *,
    directions: pd.DataFrame,
    edges: np.ndarray,
    weight_mode: str,
    chunk_size: int = 128,
    fixed_axis: dict | None = None,
    axis_objective: str = "dipole",
    zbin_axis_mode: str = "fixed_global",
) -> pd.DataFrame:
    """Extrinsic statistics in redshift bins.

    By default (``zbin_axis_mode='fixed_global'``), every redshift bin is
    evaluated on the same full-catalogue axis supplied in ``fixed_axis``.  This
    is the paper/test mode: the axis can be the one maximizing either the
    dipolar handedness or the axial CCW/CW sign asymmetry.  The legacy
    ``zbin_axis_mode='per_bin_max'`` independently scans each bin and is kept as
    a diagnostic only.
    """
    work = d.copy()
    w_all = arm_weights(work, weight_mode)
    z = work["z_eff"].to_numpy(float)
    h_all = work["S_tangential"].to_numpy(float)
    xyz_all = unit_xyz_from_radec(work["ra"].to_numpy(float), work["dec"].to_numpy(float))
    axis_objective = str(axis_objective).lower()
    zbin_axis_mode = str(zbin_axis_mode).lower()
    rows = []
    for ib in range(len(edges) - 1):
        z0, z1 = float(edges[ib]), float(edges[ib + 1])
        if ib == len(edges) - 2:
            m = np.isfinite(z) & np.isfinite(h_all) & (z >= z0) & (z <= z1)
        else:
            m = np.isfinite(z) & np.isfinite(h_all) & (z >= z0) & (z < z1)
        ok = m & np.isfinite(w_all) & (w_all > 0)
        nbin = int(np.count_nonzero(ok))
        if nbin == 0:
            rows.append({"zbin_id": ib, "z_min": z0, "z_max": z1, "z_center": 0.5*(z0+z1), "n_arms": 0})
            continue

        if zbin_axis_mode in {"per_bin", "per_bin_max", "legacy"}:
            scan_b = scan_axis_grid(
                arm_xyz=xyz_all[ok], sphi=h_all[ok], directions=directions, weights=w_all[ok],
                chunk_size=chunk_size, progress=False,
            )
            axis_b = best_axis_from_scan(scan_b, objective=axis_objective)
        else:
            if fixed_axis is None:
                raise ValueError("fixed_axis is required when zbin_axis_mode='fixed_global'")
            axis_b = fixed_axis

        stats = _stats_for_fixed_axis_subset(xyz_all[ok], h_all[ok], w_all[ok], axis_b)
        rows.append({
            "zbin_id": ib,
            "z_min": z0,
            "z_max": z1,
            "z_center": float(np.nanmean(z[ok])) if np.any(np.isfinite(z[ok])) else 0.5*(z0+z1),
            "z_bin_center": 0.5*(z0+z1),
            "n_arms": nbin,
            "ra_deg": float(axis_b["ra_deg"]),
            "dec_deg": float(axis_b["dec_deg"]),
            "axis_objective": axis_objective,
            "zbin_axis_mode": zbin_axis_mode,
            **stats,
        })
    return pd.DataFrame(rows)



def make_healpix_map(scan: pd.DataFrame, *, nside: int, value_col: str = "H_ext") -> np.ndarray:
    require_healpy()
    npix = hp.nside2npix(int(nside))
    mp = np.full(npix, hp.UNSEEN, dtype=float)
    pix = scan["pix"].to_numpy(int)
    val = scan[value_col].to_numpy(float)
    mp[pix] = val
    # Fill antipodal pixels with the opposite H value because H(-d) = -H(d).
    theta, phi = hp.pix2ang(int(nside), pix, nest=False)
    theta2 = np.pi - theta
    phi2 = (phi + np.pi) % (2*np.pi)
    pix2 = hp.ang2pix(int(nside), theta2, phi2, nest=False)
    mp[pix2] = -val
    return mp


