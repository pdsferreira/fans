def _projected_global_signflip_sigmas_by_catalog(
    projected: list[tuple[str, str, pd.DataFrame]],
    statistic: str,
    *,
    B: int = 1000,
    block_nside: int = 16,
    seed: int = 20260701,
) -> list[tuple[str, str, float]]:
    """Full-range projected significance from a block sign-flip null.

    This is the projected analogue of the unbinned/full-range extrinsic labels.
    It uses all accepted arms in the full redshift interval covered by the
    plotted z-bins, randomizes the handedness sign coherently per HEALPix block,
    and compares the observed full-range statistic against |null|.

    The returned Gaussian-equivalent Z is two-sided because the projected
    handedness and CCW/CW sign asymmetry have no pre-selected positive direction.
    """
    out = []
    try:
        from . import pipeline as _pipe
    except Exception as exc:
        print(f"[warn] projected global sign-flip unavailable: {exc!r}")
        return [(key, label, np.nan) for key, label, _d in projected]

    for key, label, summ in projected:
        zsig = np.nan
        try:
            if summ is None or len(summ) == 0:
                out.append((key, label, zsig)); continue
            tab_path, weight_mode = _pipe._infer_measurement_table_and_weight(summ)
            if tab_path is None or not Path(tab_path).exists():
                out.append((key, label, zsig)); continue

            # Prefer the authoritative joint null ensemble, not a fresh plot-only draw.
            from scipy.stats import norm
            for ancestor in Path(tab_path).parents:
                official = ancestor / "paper_tables" / "projected_significance_joint.csv"
                if official.exists():
                    nt = pd.read_csv(official)
                    stat_key = "H" if statistic == "H" else "A_sign"
                    sel = nt[(nt.catalog == key) & (nt.zbin_id == -1) &
                             (nt.stratum == "all") & (nt.statistic == stat_key)]
                    if len(sel) == 1:
                        p = float(sel.iloc[0]["p_two_sided"])
                        zsig = float(norm.isf(p / 2.0)) if np.isfinite(p) else np.nan
                    break
            if np.isfinite(zsig):
                out.append((key, label, zsig)); continue

            d = _pipe.normalise_measurement_columns(pd.read_csv(tab_path))
            if "status" in d.columns:
                st = d["status"].astype(str).str.lower()
                keep = st.eq("ok")
                d = d.loc[keep].copy()
            if "S_tangential" not in d.columns or len(d) == 0:
                out.append((key, label, zsig)); continue

            z = _pipe.robust_z_center(d)
            z0 = float(np.nanmin(pd.to_numeric(summ.get("z_min"), errors="coerce"))) if "z_min" in summ.columns else np.nan
            z1 = float(np.nanmax(pd.to_numeric(summ.get("z_max"), errors="coerce"))) if "z_max" in summ.columns else np.nan
            mask = np.isfinite(z)
            if np.isfinite(z0):
                mask &= z >= z0
            if np.isfinite(z1):
                mask &= z <= z1
            d = d.loc[mask].copy().reset_index(drop=True)
            if len(d) == 0:
                out.append((key, label, zsig)); continue

            h = pd.to_numeric(d["S_tangential"], errors="coerce").to_numpy(float)
            w = _pipe.summary_weights(d, weight_mode)
            blocks = _pipe.assign_healpix_blocks(d, int(block_nside))
            ok = np.isfinite(h) & np.isfinite(w) & (w > 0)
            if str(statistic).lower().startswith("sign"):
                ok &= (h != 0.0)
            h, w, blocks = h[ok], w[ok], blocks[ok]
            if len(h) == 0:
                out.append((key, label, zsig)); continue

            if str(statistic).lower().startswith("sign"):
                obs = 100.0 * float(np.mean(np.sign(h)))
            else:
                obs = _pipe.weighted_mean_np(h, w)
            if not np.isfinite(obs):
                out.append((key, label, zsig)); continue

            rng = np.random.default_rng(int(seed) + _pipe._catalog_seed_offset(str(key)))
            ub, inv = np.unique(blocks, return_inverse=True)
            vals = np.empty(int(B), dtype=float)
            for b in range(int(B)):
                eps = rng.choice(np.array([-1.0, 1.0]), size=len(ub), replace=True)
                hh = h * eps[inv]
                if str(statistic).lower().startswith("sign"):
                    vals[b] = 100.0 * float(np.mean(np.sign(hh)))
                else:
                    vals[b] = _pipe.weighted_mean_np(hh, w)
            vals = vals[np.isfinite(vals)]
            if len(vals):
                pval = (1.0 + np.count_nonzero(np.abs(vals) >= abs(float(obs)))) / (len(vals) + 1.0)
                zsig = _normal_two_sided_z_from_p(pval)
        except Exception as exc:
            print(f"[warn] projected global sign-flip sigma failed for {key}/{statistic}: {exc!r}")
        out.append((key, label, zsig))
    return out


