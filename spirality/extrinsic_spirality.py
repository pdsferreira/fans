def pchip_curve(x: np.ndarray, y: np.ndarray, n: int = 256) -> tuple[np.ndarray, np.ndarray]:
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)
    ok = np.isfinite(x) & np.isfinite(y)
    x, y = x[ok], y[ok]
    if len(x) < 2:
        return x, y
    order = np.argsort(x)
    x, y = x[order], y[order]
    if PchipInterpolator is not None and len(x) >= 3:
        xx = np.linspace(float(np.nanmin(x)), float(np.nanmax(x)), n)
        yy = PchipInterpolator(x, y, extrapolate=False)(xx)
    else:
        xx = np.linspace(float(np.nanmin(x)), float(np.nanmax(x)), n)
        yy = np.interp(xx, x, y)
    return xx, yy


def plot_one_series_pchip(ax, df: pd.DataFrame, key: str, label: str, ycol: str, errcol: str, *, angle: bool = False, extband: bool = False) -> pd.DataFrame:
    st = STYLE[key]
    x = df["z_center"].to_numpy(float)
    zlo = df["z_min"].to_numpy(float)
    zhi = df["z_max"].to_numpy(float)
    y = df[ycol].to_numpy(float)
    e = df[errcol].to_numpy(float) if errcol in df.columns else np.full_like(y, np.nan)
    lo, hi = y - e, y + e
    if angle:
        # ycol already angle in this script; errcol already angle error.
        pass
    good = np.isfinite(x) & np.isfinite(y)
    good_band = good & np.isfinite(lo) & np.isfinite(hi)
    if np.count_nonzero(good_band) >= 2:
        xb, lob, hib = x[good_band].copy(), lo[good_band].copy(), hi[good_band].copy()
        if extband:
            zglo, zghi = zlo[good_band], zhi[good_band]
            order = np.argsort(xb)
            xb, lob, hib, zglo, zghi = xb[order], lob[order], hib[order], zglo[order], zghi[order]
            if np.isfinite(zglo[0]) and zglo[0] < xb[0]:
                xb = np.insert(xb, 0, zglo[0]); lob = np.insert(lob, 0, lob[0]); hib = np.insert(hib, 0, hib[0])
            if np.isfinite(zghi[-1]) and zghi[-1] > xb[-1]:
                xb = np.append(xb, zghi[-1]); lob = np.append(lob, lob[-1]); hib = np.append(hib, hib[-1])
        xs_lo, ys_lo = pchip_curve(xb, lob)
        xs_hi, ys_hi = pchip_curve(xb, hib)
        if len(xs_lo) == len(xs_hi):
            ax.fill_between(xs_lo, ys_lo, ys_hi, color=st["fill"], alpha=0.34, lw=0, zorder=st["z"])
            ax.plot(xs_lo, ys_lo, color=st["line"], lw=1.05, alpha=0.78, zorder=st["z"]+0.1)
            ax.plot(xs_hi, ys_hi, color=st["line"], lw=1.05, alpha=0.78, zorder=st["z"]+0.1)
        for xx, yy0, yy1 in zip(x[good_band], lo[good_band], hi[good_band]):
            ax.plot([xx, xx], [yy0, yy1], color=st["line"], lw=1.05, alpha=0.70, zorder=st["z"]+0.35)

    if np.count_nonzero(good) >= 2:
        xline = x[good].copy(); yline = y[good].copy()
        visible_min, visible_max = float(np.nanmin(xline)), float(np.nanmax(xline))
        if extband:
            zlg, zhg = zlo[good].copy(), zhi[good].copy()
            order = np.argsort(xline)
            xline, yline, zlg, zhg = xline[order], yline[order], zlg[order], zhg[order]
            if np.isfinite(zlg[0]) and zlg[0] < xline[0]:
                xline = np.insert(xline, 0, zlg[0]); yline = np.insert(yline, 0, yline[0])
            if np.isfinite(zhg[-1]) and zhg[-1] > xline[-1]:
                xline = np.append(xline, zhg[-1]); yline = np.append(yline, yline[-1])
        xs, ys = pchip_curve(xline, yline)
        if extband:
            vis = (xs >= visible_min) & (xs <= visible_max)
            xs, ys = xs[vis], ys[vis]
        ax.plot(xs, ys, ls=_catalog_linestyle(key), lw=1.35, color=st["line"], alpha=0.82, zorder=st["z"]+0.75)

    for xx0, xx1, yy in zip(zlo[good], zhi[good], y[good]):
        ax.plot([xx0, xx1], [yy, yy], color=st["line"], lw=1.0, alpha=0.58, zorder=st["z"]+0.55)
    ax.plot(x[good], y[good], ls="none", marker=st["marker"], ms=st["ms"], color=st["line"], label=label, zorder=st["z"]+1)
    return pd.DataFrame({"catalog": label, "catalog_key": key, "z_min": zlo, "z_max": zhi, "z_center": x, "y": y, "y_low": lo, "y_high": hi})


