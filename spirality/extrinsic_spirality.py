def _zbin_pvalues_to_sigma(pvals: list[float], *, method: str = "z_quadrature", one_sided: bool = True) -> float:
    """Combine z-bin p-values into one compact panel significance.

    This helper is deliberately for *panel annotation*, not a replacement for
    the tabulated mock-calibrated p-values.  Available modes:

    - ``fisher``: classical Fisher combination of p-values.  This is a valid
      global null test, but bins with p~1 contribute little while still
      increasing the degrees of freedom, so it can look conservative when the
      signal is localized in only a subset of bins.
    - ``stouffer``: average positive one-sided Z values as sum(Z_i)/sqrt(k).
    - ``z_quadrature``: combine positive one-sided Z values as sqrt(sum Z_i^2).
      This behaves like an S/N-in-quadrature diagnostic and does not penalize
      bins that are simply consistent with the null.
    - ``min_p_sidak``: use the most significant bin with a Sidak trials
      correction for the number of bins.
    - ``max``: show the most significant bin without a trials correction.

    For the extrinsic amplitudes used here the relevant per-bin p-values are
    one-sided/look-elsewhere p-values from the sign-flip mocks.
    """
    vals = [float(p) for p in pvals if np.isfinite(p) and 0.0 < float(p) <= 1.0]
    if not vals:
        return np.nan
    method = str(method).lower()
    if method == "fisher":
        p_comb = _fisher_pvalue_from_pvalues(vals)
        return _normal_one_sided_z_from_p(p_comb) if one_sided else _normal_two_sided_z_from_p(p_comb)

    if method in {"stouffer", "z_stouffer"}:
        zs = np.array([_normal_one_sided_z_from_p(p) for p in vals], dtype=float)
        zs = zs[np.isfinite(zs)]
        if len(zs) == 0:
            return np.nan
        return float(np.sum(zs) / np.sqrt(len(zs)))

    if method in {"z_quadrature", "quadrature", "rss", "snr_quadrature"}:
        zs = np.array([_normal_one_sided_z_from_p(p) for p in vals], dtype=float)
        zs = zs[np.isfinite(zs)]
        if len(zs) == 0:
            return np.nan
        # Detection significances are non-negative by definition.  The RSS
        # combination must therefore be at least as large as the most
        # significant individual bin; keep this explicit to make the panel
        # annotation robust to future changes in the p-to-Z converter.
        zs = np.maximum(zs, 0.0)
        zq = float(np.sqrt(np.sum(zs * zs)))
        return float(max(zq, float(np.nanmax(zs))))

    if method in {"min_p_sidak", "sidak", "minp"}:
        pmin = float(np.min(vals))
        p_corr = 1.0 - (1.0 - pmin) ** len(vals)
        return _normal_one_sided_z_from_p(p_corr) if one_sided else _normal_two_sided_z_from_p(p_corr)

    if method in {"max", "best_bin"}:
        pmin = float(np.min(vals))
        return _normal_one_sided_z_from_p(pmin) if one_sided else _normal_two_sided_z_from_p(pmin)

    raise ValueError(f"Unknown z-bin p-value combination method: {method}")


def _sigmas_from_zbin_pvalues_by_catalog(
    datasets: list[tuple[str, str, pd.DataFrame, dict]],
    pkey: str,
    *,
    one_sided: bool = True,
    method: str = "z_quadrature",
) -> list[tuple[str, str, float]]:
    """Combine redshift-bin p-values within each catalogue.

    Carrón and Chen are never combined with each other here; each catalogue gets
    its own sigma annotation.  The default ``z_quadrature`` is a compact
    positive-S/N diagnostic across redshift bins.  For a strict global p-value
    under independent bins, use ``method='fisher'``; for a strongest-bin
    diagnostic use ``method='min_p_sidak'``.
    """
    out = []
    for key, label, zdf, _best in datasets:
        z = np.nan
        if zdf is not None and len(zdf) and pkey in zdf.columns:
            pvals = pd.to_numeric(zdf[pkey], errors="coerce").to_numpy(float)
            pvals = [float(p) for p in pvals if np.isfinite(p) and 0.0 < p <= 1.0]
            if pvals:
                z = _zbin_pvalues_to_sigma(pvals, method=method, one_sided=one_sided)
        out.append((key, label, z))
    return out





def _sigmas_signed_inverse_variance_from_zbins_by_catalog(
    datasets: list[tuple[str, str, pd.DataFrame, dict]],
    value_col: str,
    err_col: str,
    *,
    pkey: str | None = None,
) -> list[tuple[str, str, float]]:
    """Coherent signed z-bin significance for panel annotations.

    Earlier development versions used the analytic amplitude errors directly as
    ``|sum A_i/sigma_i^2|/sqrt(sum 1/sigma_i^2)``.  That can wildly overstate
    the panel label when the analytic ``sigma_i`` is small compared with the
    look-elsewhere/mock-calibrated p-value.  For the paper panel, the displayed
    significance should remain tied to the mock/sign-flip p-values.

    This helper therefore builds a signed Stouffer statistic from the per-bin
    one-sided look-elsewhere p-values, with signs taken from ``value_col``:

        Z_i = max(0, Phi^{-1}(1-p_i)),
        Z = |sum_i sign(A_i) Z_i| / sqrt(N).

    If ``pkey`` is unavailable, it falls back to the old analytic formula, but
    caps the result at the quadrature combination of the per-bin analytic S/Ns
    to avoid pathological labels.
    """
    out = []
    for key, label, zdf, _best in datasets:
        z = np.nan
        if zdf is not None and len(zdf) and value_col in zdf.columns:
            y = pd.to_numeric(zdf[value_col], errors="coerce").to_numpy(float)
            # Preferred: signed Stouffer from mock/look-elsewhere p-values.
            if pkey is not None and pkey in zdf.columns:
                p = pd.to_numeric(zdf[pkey], errors="coerce").to_numpy(float)
                ok = np.isfinite(y) & np.isfinite(p) & (p > 0.0) & (p <= 1.0)
                if np.any(ok):
                    signs = np.sign(y[ok])
                    signs[signs == 0] = 1.0
                    zi = np.array([_normal_one_sided_z_from_p(pp) for pp in p[ok]], dtype=float)
                    zi = np.maximum(zi, 0.0)
                    good = np.isfinite(zi)
                    if np.any(good):
                        z = float(abs(np.sum(signs[good] * zi[good])) / np.sqrt(np.sum(good)))
            # Fallback only if no p-values are available.
            if not np.isfinite(z) and err_col in zdf.columns:
                e = pd.to_numeric(zdf[err_col], errors="coerce").to_numpy(float)
                ok = np.isfinite(y) & np.isfinite(e) & (e > 0)
                if np.any(ok):
                    sn = y[ok] / e[ok]
                    w = 1.0 / np.square(e[ok])
                    num = float(np.sum(w * y[ok]))
                    den = float(np.sqrt(np.sum(w)))
                    z_ivw = abs(num) / den if den > 0 and np.isfinite(num) else np.nan
                    z_rss = float(np.sqrt(np.sum(np.square(np.maximum(np.abs(sn), 0.0)))))
                    if np.isfinite(z_ivw):
                        z = float(min(z_ivw, z_rss))
        out.append((key, label, z))
    return out


def _axis_vec_from_radec_scalar(ra_deg: float, dec_deg: float) -> np.ndarray:
    """Unit vector for one sky direction, or NaNs if invalid."""
    if not np.isfinite(ra_deg) or not np.isfinite(dec_deg):
        return np.array([np.nan, np.nan, np.nan], dtype=float)
    return unit_xyz_from_radec(np.array([float(ra_deg)]), np.array([float(dec_deg)]))[0]


def _radec_near_reference(ra_deg: float, dec_deg: float, ref_vec: np.ndarray) -> tuple[float, float]:
    """Orient an axial direction so it is as close as possible to ref_vec."""
    v = _axis_vec_from_radec_scalar(float(ra_deg), float(dec_deg))
    if not np.all(np.isfinite(v)) or not np.all(np.isfinite(ref_vec)):
        return float(ra_deg), float(dec_deg)
    if float(np.dot(v, ref_vec)) < 0.0:
        return _antipode_radec(float(ra_deg), float(dec_deg))
    return float(ra_deg) % 360.0, float(dec_deg)


def _axis_error_columns_for_bingham(zdf: pd.DataFrame, error_source: str = "objective") -> tuple[str, str]:
    """Return value/error columns used to estimate angular width per bin.

    For dipole-axis fits we use atan(H_ext_err/H_ext).  For axial-sign-axis
    fits, the default objective-aware choice uses the binomial sign-asymmetry
    uncertainty atan(sigma_A/A) with A expressed in percent.  The command-line
    option can force either choice.
    """
    source = str(error_source).lower().strip()
    objective = "dipole"
    if zdf is not None and "axis_objective" in zdf.columns and len(zdf):
        vals = [str(v).lower() for v in zdf["axis_objective"].dropna().unique()]
        if vals:
            objective = vals[0]
    if source in {"dipole", "h", "h_ext", "a_dip"}:
        return "H_ext", "H_ext_err"
    if source in {"axial_sign", "sign", "sign_asym", "sign_asymmetry"}:
        return "sign_asym_ext_percent", "sign_asym_ext_percent_err"
    if source in {"objective", "auto"}:
        if objective in {"axial_sign", "sign", "sign_asym", "sign_asymmetry"}:
            return "sign_asym_ext_percent", "sign_asym_ext_percent_err"
        return "H_ext", "H_ext_err"
    raise ValueError(f"Unknown axis-bingham error source: {error_source!r}")


def _per_bin_axis_measurements_for_bingham(
    zdf: pd.DataFrame,
    *,
    error_source: str = "objective",
    min_sigma_deg: float = 0.35,
    max_sigma_deg: float = 89.0,
) -> list[dict]:
    """Per-bin axial directions and angular errors for Bingham combination.

    The angular width is estimated as

        sigma_theta = atan(sigma_A / |A|),

    where A is H_ext for the dipole objective, or the axial sign asymmetry for
    the axial-sign objective.  The returned sigma is a 1-sigma angular width;
    the per-bin legend quotes approximately 2*sigma as a 95% CI.
    """
    if zdf is None or len(zdf) == 0:
        return []
    d = zdf.copy()
    if "zbin_id" in d.columns:
        d = d.sort_values("zbin_id")
    elif "z_center" in d.columns:
        d = d.sort_values("z_center")
    if "ra_deg" not in d.columns or "dec_deg" not in d.columns:
        return []
    val_col, err_col = _axis_error_columns_for_bingham(d, error_source=error_source)
    out = []
    for _, row in d.iterrows():
        ra = _safe_float_from_mapping(row, "ra_deg")
        dec = _safe_float_from_mapping(row, "dec_deg")
        if not np.isfinite(ra) or not np.isfinite(dec):
            continue
        amp = abs(_safe_float_from_mapping(row, val_col))
        err = abs(_safe_float_from_mapping(row, err_col))
        if not np.isfinite(amp) or amp <= 0 or not np.isfinite(err) or err <= 0:
            sigma_deg = max_sigma_deg
        else:
            sigma_deg = float(np.rad2deg(np.arctan2(err, max(amp, 1e-15))))
            sigma_deg = float(np.clip(sigma_deg, min_sigma_deg, max_sigma_deg))
        theta95 = float(min(90.0, 2.0 * sigma_deg))
        vec = _axis_vec_from_radec_scalar(ra, dec)
        if not np.all(np.isfinite(vec)):
            continue
        out.append({
            "zbin_id": int(row.get("zbin_id", len(out))),
            "z_min": _safe_float_from_mapping(row, "z_min"),
            "z_max": _safe_float_from_mapping(row, "z_max"),
            "ra_deg": float(ra % 360.0),
            "dec_deg": float(dec),
            "x": float(vec[0]),
            "y": float(vec[1]),
            "z": float(vec[2]),
            "axis_error_value_col": val_col,
            "axis_error_err_col": err_col,
            "axis_error_amp": float(amp) if np.isfinite(amp) else np.nan,
            "axis_error_sigma": float(err) if np.isfinite(err) else np.nan,
            "sigma_theta_deg": sigma_deg,
            "theta95_deg": theta95,
            "n_arms": int(row.get("n_arms", 0)) if np.isfinite(row.get("n_arms", np.nan)) else 0,
        })
    return out


def _bingham_combine_axes(
    measurements: list[dict],
    *,
    nside: int = 64,
) -> dict:
    r"""Combine axial sky directions with a simple Bingham likelihood.

    Each bin contributes

        L_i(n) \propto exp[kappa_i (n . n_i)^2],

    with kappa_i = 1/(2 sigma_theta_i^2), where sigma_theta_i is estimated from
    atan(sigma_A/A).  The likelihood is evaluated on the axial HEALPix grid used
    by the scan.  The returned 68/95 errors are HPD angular radii around the
    maximum direction.  This is a composite likelihood; it should be interpreted
    as a directional summary rather than an independently calibrated p-value.
    """
    require_healpy()
    rows = [m for m in measurements if np.all(np.isfinite([m.get("x", np.nan), m.get("y", np.nan), m.get("z", np.nan)]))]
    if not rows:
        return {}
    dirs = healpix_direction_grid(int(nside))
    grid_xyz = dirs[["x", "y", "z"]].to_numpy(float)
    logL = np.zeros(len(grid_xyz), dtype=float)
    used = 0
    for m in rows:
        sigma_rad = np.deg2rad(float(m.get("sigma_theta_deg", np.nan)))
        if not np.isfinite(sigma_rad) or sigma_rad <= 0:
            continue
        sigma_rad = float(np.clip(sigma_rad, np.deg2rad(0.35), np.deg2rad(89.0)))
        kappa = 1.0 / (2.0 * sigma_rad * sigma_rad)
        v = np.array([m["x"], m["y"], m["z"]], dtype=float)
        v = v / np.linalg.norm(v)
        mu = grid_xyz @ v
        logL += kappa * mu * mu
        m["bingham_kappa"] = float(kappa)
        used += 1
    if used == 0:
        return {}
    imax = int(np.nanargmax(logL))
    best_vec = grid_xyz[imax]
    best_ra = float(dirs.iloc[imax]["ra_deg"])
    best_dec = float(dirs.iloc[imax]["dec_deg"])
    # Posterior weights on the axial half-sky grid.
    logL0 = logL - float(np.nanmax(logL))
    prob = np.exp(np.clip(logL0, -745.0, 0.0))
    prob = np.where(np.isfinite(prob), prob, 0.0)
    total = float(np.sum(prob))
    if total <= 0:
        theta68 = np.nan
        theta95 = np.nan
    else:
        prob /= total
        order = np.argsort(prob)[::-1]
        csum = np.cumsum(prob[order])
        # Axial angular distance to the best direction.
        cosang = np.clip(np.abs(grid_xyz @ best_vec), -1.0, 1.0)
        ang = np.rad2deg(np.arccos(cosang))
        def _hpd_radius(level: float) -> float:
            idx = int(np.searchsorted(csum, float(level), side="left"))
            idx = min(max(idx, 0), len(order) - 1)
            region = order[:idx + 1]
            return float(np.nanmax(ang[region])) if len(region) else np.nan
        theta68 = _hpd_radius(0.6827)
        theta95 = _hpd_radius(0.9545)
    return {
        "ra_deg": best_ra,
        "dec_deg": best_dec,
        "x": float(best_vec[0]),
        "y": float(best_vec[1]),
        "z": float(best_vec[2]),
        "n_bins_used": int(used),
        "theta68_deg": float(theta68) if np.isfinite(theta68) else np.nan,
        "theta95_deg": float(theta95) if np.isfinite(theta95) else np.nan,
        "nside": int(nside),
        "method": "bingham",
    }


def _format_axis_pair(ra: float, dec: float, theta95: float | None = None) -> str:
    """Compact axis pair with a 95% angular radius on the sphere.

    ``theta95`` is an angular radius, not independent RA/Dec error bars.  Near
    the poles, converting a circular angular uncertainty into RA coordinates
    requires a Jacobian factor ~1/cos(dec) and can become misleading.
    """
    if not np.isfinite(ra) or not np.isfinite(dec):
        return "unavailable"
    if theta95 is not None and np.isfinite(theta95):
        return f"({ra:.0f}°, {dec:.0f}°), r95={theta95:.0f}°"
    return f"({ra:.0f}°, {dec:.0f}°)"


def _bingham_axis_summary_for_dataset(
    key: str,
    label: str,
    zdf: pd.DataFrame,
    *,
    nside: int = 64,
    error_source: str = "objective",
) -> tuple[str, list[dict], dict]:
    """Formatted per-bin + combined Bingham-axis summary for one catalogue."""
    meas = _per_bin_axis_measurements_for_bingham(zdf, error_source=error_source)
    comb = _bingham_combine_axes(meas, nside=nside) if meas else {}
    short = _sigma_label_from_catalog_key(key, label)
    if not meas:
        return f"{short}: axes unavailable", [], {}
    ref_vec = np.array([comb.get("x", np.nan), comb.get("y", np.nan), comb.get("z", np.nan)], dtype=float)
    if not np.all(np.isfinite(ref_vec)):
        ref_vec = np.array([meas[0]["x"], meas[0]["y"], meas[0]["z"]], dtype=float)
    parts = []
    for m in meas:
        ra_d, dec_d = _radec_near_reference(m["ra_deg"], m["dec_deg"], ref_vec)
        m["ra_deg_display"] = float(ra_d)
        m["dec_deg_display"] = float(dec_d)
        parts.append(f"b{int(m['zbin_id'])+1} " + _format_axis_pair(ra_d, dec_d, m.get("theta95_deg", np.nan)))
    line_bins = f"{short} bins: " + "; ".join(parts)
    if comb:
        ra_c, dec_c = _radec_near_reference(comb["ra_deg"], comb["dec_deg"], ref_vec)
        comb["ra_deg_display"] = float(ra_c)
        comb["dec_deg_display"] = float(dec_c)
        line_comb = f"{short} comb.: " + _format_axis_pair(ra_c, dec_c, comb.get("theta95_deg", np.nan))
    else:
        line_comb = f"{short} comb.: unavailable"
    return line_bins + "\n" + line_comb, meas, comb


