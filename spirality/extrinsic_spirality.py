def _total_sigma_inverse_variance(dfs: list[pd.DataFrame], value_col: str, err_col: str) -> float:
    """Approximate total detection significance by inverse-variance combining bins.

    This is used only for the compact visual label in the summary panel.  The
    table products remain the authoritative source for exact p-values/null tests.
    """
    ys = []
    es = []
    for df in dfs:
        if df is None or len(df) == 0 or value_col not in df.columns or err_col not in df.columns:
            continue
        y = pd.to_numeric(df[value_col], errors="coerce").to_numpy(float)
        e = pd.to_numeric(df[err_col], errors="coerce").to_numpy(float)
        ok = np.isfinite(y) & np.isfinite(e) & (e > 0)
        if np.any(ok):
            ys.append(y[ok]); es.append(e[ok])
    if not ys:
        return np.nan
    y = np.concatenate(ys)
    e = np.concatenate(es)
    w = 1.0 / np.square(e)
    if np.sum(w) <= 0:
        return np.nan
    ybar = float(np.sum(w * y) / np.sum(w))
    sigma = float(1.0 / np.sqrt(np.sum(w)))
    return abs(ybar / sigma) if sigma > 0 and np.isfinite(sigma) else np.nan


def _fisher_pvalue_from_pvalues(pvals: list[float]) -> float:
    """Fisher-combine a list of p-values.

    This helper is used only for compact panel annotations.  In the paper
    extrinsic panel, the default is to combine the four redshift-bin p-values
    within each catalogue, not to combine Carrón and Chen with each other.

    If SciPy is available, use the standard Fisher statistic
    ``X=-2 sum(log p_i)`` with ``2k`` degrees of freedom.  The one-p-value case
    returns that p-value unchanged.
    """
    vals = [float(p) for p in pvals if np.isfinite(p) and 0.0 < float(p) <= 1.0]
    if not vals:
        return np.nan
    if len(vals) == 1:
        return vals[0]
    x = -2.0 * float(np.sum(np.log(vals)))
    try:
        from scipy.stats import chi2
        return float(chi2.sf(x, 2 * len(vals)))
    except Exception:
        # Fallback for the common two-p-value case.  For larger k, return the
        # minimum p-value as a conservative visual diagnostic.
        if len(vals) == 2:
            return float(np.exp(-0.5 * x) * (1.0 + 0.5 * x))
        return float(min(vals))


