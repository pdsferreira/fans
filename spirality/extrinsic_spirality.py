def _format_sigma_lines(items: list[tuple[str, str, float]], *, truncate_negative: bool = False) -> str:
    """Format one sigma line per catalogue for compact panel annotations.

    Values below 0.1σ are displayed as ``<0.1`` rather than ``0.0``.
    This is clearer for positive/look-elsewhere statistics whose observed value
    is non-zero but less extreme than the median null realization.
    """
    lines = []
    for key, label, sigma in items:
        try:
            z = float(sigma)
        except Exception:
            continue
        if not np.isfinite(z):
            continue
        if truncate_negative:
            z = max(0.0, z)
        tag = _sigma_label_from_catalog_key(key, label)
        if z < 0.1:
            lines.append(rf"$\sigma_{{\rm {tag}}}<0.1$")
        else:
            lines.append(rf"$\sigma_{{\rm {tag}}}={z:.1f}$")
    return "\n".join(lines)


