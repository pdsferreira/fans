def math_pm(val: float, ep: float, em: float, *, nd: int, unit: str = "") -> str:
    """Mathtext-safe asymmetric error, with grouped base value."""
    return rf"{{{val:.{nd}f}}}^{{+{ep:.{nd}f}}}_{{-{em:.{nd}f}}}{unit}"


def format_bestfit_label(label: str, best: dict) -> str:
    """Compact mathtext label for the extrinsic panel."""
    lab = short_catalog_label(label)
    ra = float(best.get("ra_deg_display", best.get("ra_deg", np.nan)))
    dec = float(best.get("dec_deg_display", best.get("dec_deg", np.nan)))
    h = float(best.get("H_ext", np.nan))

    if all(k in best for k in ["ra_deg_err_minus", "ra_deg_err_plus", "dec_deg_err_minus", "dec_deg_err_plus", "H_ext_err_minus", "H_ext_err_plus"]):
        return (
            rf"{lab}: "
            rf"$\alpha={math_pm(ra, float(best['ra_deg_err_plus']), float(best['ra_deg_err_minus']), nd=1, unit=r'\,{\rm deg}')}$, "
            rf"$\delta={math_pm(dec, float(best['dec_deg_err_plus']), float(best['dec_deg_err_minus']), nd=1, unit=r'\,{\rm deg}')}$, "
            rf"$H_{{\rm ext}}={math_pm(h, float(best['H_ext_err_plus']), float(best['H_ext_err_minus']), nd=3)}$"
        )
    return rf"{lab}: $\alpha={ra:.1f}\,{{\rm deg}}$, $\delta={dec:.1f}\,{{\rm deg}}$, $H_{{\rm ext}}={h:.3f}$"


def _pchip_noise_curve_ext(x: np.ndarray, y: np.ndarray, zlo: np.ndarray, zhi: np.ndarray, *, extband: bool) -> tuple[np.ndarray, np.ndarray]:
    good = np.isfinite(x) & np.isfinite(y)
    if np.count_nonzero(good) < 2:
        return np.array([]), np.array([])
    xline = x[good].copy()
    yline = y[good].copy()
    if extband:
        zl = zlo[good].copy()
        zh = zhi[good].copy()
        order = np.argsort(xline)
        xline, yline, zl, zh = xline[order], yline[order], zl[order], zh[order]
        if np.isfinite(zl[0]) and zl[0] < xline[0]:
            xline = np.insert(xline, 0, zl[0])
            yline = np.insert(yline, 0, yline[0])
        if np.isfinite(zh[-1]) and zh[-1] > xline[-1]:
            xline = np.append(xline, zh[-1])
            yline = np.append(yline, yline[-1])
    return pchip_curve(xline, yline)


def _draw_extrinsic_lookelsewhere_lines(ax, df: pd.DataFrame, key: str, *, panel: str, angle: bool, extband: bool) -> Optional[pd.DataFrame]:
    """Draw look-elsewhere null thresholds on an extrinsic panel.

    The signed dipole and axial-sign nulls repeat the global dipole-axis
    selection. Symmetric envelopes enclose 68.27% and 95.45% of the absolute
    null distribution; this plotting convention is distinct from converting a
    global empirical tail p-value into a one- or two-sided Gaussian-equivalent Z.
    """
    x = df["z_center"].to_numpy(float)
    zlo = df["z_min"].to_numpy(float)
    zhi = df["z_max"].to_numpy(float)

    if panel == "H":
        qcols = [
            (["lookelsewhere_H_q1sigma", "lookelsewhere_H_q68"], "q1sigma", 1.25, 0.43),
            (["lookelsewhere_H_q2sigma", "lookelsewhere_H_q95"], "q2sigma", 1.85, 0.78),
        ]
    else:
        qcols = [
            (["lookelsewhere_sign_percent_q1sigma", "lookelsewhere_sign_percent_q68"], "q1sigma", 1.25, 0.43),
            (["lookelsewhere_sign_percent_q2sigma", "lookelsewhere_sign_percent_q95"], "q2sigma", 1.85, 0.78),
        ]

    rows = []
    drew_any = False
    ls = _catalog_linestyle(key)
    for candidates, qlabel, lw, alpha in qcols:
        col = next((c for c in candidates if c in df.columns), None)
        if col is None:
            continue
        y = pd.to_numeric(df[col], errors="coerce").to_numpy(float)
        if panel == "H" and angle:
            y = _asin_deg_clip(y)
        xs, ys = _pchip_noise_curve_ext(x, y, zlo, zhi, extband=extband)
        if len(xs) == 0:
            continue
        # Positive and negative thresholds.  For the dipole-amplitude panel the
        # negative branch will usually fall outside the plotted range, but we
        # keep the symmetric convention for consistency.
        ax.plot(xs, ys, ls=ls, lw=lw, color="black", alpha=alpha, zorder=-4)
        ax.plot(xs, -ys, ls=ls, lw=lw, color="black", alpha=alpha, zorder=-4)
        rows.append(pd.DataFrame({
            "catalog_key": key,
            "z_min": zlo,
            "z_max": zhi,
            "z_center": x,
            f"{panel}_lookelsewhere_{qlabel}": y,
        }))
        drew_any = True

    if not drew_any:
        return None
    return pd.concat(rows, ignore_index=True) if rows else None



