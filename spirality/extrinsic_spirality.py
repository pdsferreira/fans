def _asin_deg_clip(v):
    arr = np.asarray(v, dtype=float)
    return np.degrees(np.arcsin(np.where(np.abs(arr) <= 1.0, arr, np.nan)))


def _add_angle_value_error_columns(df: pd.DataFrame, value_col: str, err_col: str, out_value: str, out_err: str) -> pd.DataFrame:
    """Add asin(value) angle columns with symmetric error propagated by endpoints."""
    d = df.copy()
    if value_col not in d.columns:
        return d
    y = pd.to_numeric(d[value_col], errors="coerce").to_numpy(float)
    d[out_value] = _asin_deg_clip(y)
    if err_col in d.columns:
        e = pd.to_numeric(d[err_col], errors="coerce").to_numpy(float)
        lo = _asin_deg_clip(y - e)
        hi = _asin_deg_clip(y + e)
        d[out_err] = 0.5 * (hi - lo)
    return d




