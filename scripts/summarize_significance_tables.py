#!/usr/bin/env python3
"""Build paper-facing significance tables for projected and extrinsic FANS plots.

Projected quantities
--------------------
For the projected panels the script recomputes block sign-flip nulls directly
from ``arm_level_spirality.csv``.  The null flips the sign of handedness
coherently per HEALPix block, preserving arm positions, redshifts, weights and
|S_phi|.  It is used for the parity-odd quantities:

  * projected handedness H_proj = <S_phi>;
  * projected sign asymmetry A_sign = (N_L-N_R)/(N_L+N_R).

The parity-even spirality amplitude S_proj = <|S_phi|> is included in the table
for completeness, but its sign-flip p-values are intentionally left NaN because
sign flips leave |S_phi| invariant.  A significance for S_proj requires a
different geometric/mock null.

Extrinsic quantities
--------------------
For extrinsic panels the script reads the products generated by
``run_extrinsic_spirality.py`` and consolidates the total and per-bin
look-elsewhere p-values for:

  * dipolar extrinsic handedness H_ext / A_dip;
  * axial sign asymmetry on the dipole-selected axis.

Both one-sided and two-sided Gaussian-equivalent Z values are stored.  For the
one-sided p-value, the default is the observed direction/tail for signed
statistics and the positive tail for positive-defined amplitudes.
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Tuple

import numpy as np
import pandas as pd
from scipy.stats import norm

try:
    import healpy as hp  # type: ignore
except Exception:  # pragma: no cover
    hp = None

CATALOG_SPECS: Dict[str, Dict[str, object]] = {
    "sconce": {
        "label": "SCONCE DR17 native",
        "arm_candidates": [Path("sconce_dr17_native/arm_level_spirality.csv")],
    },
    "carron": {
        "label": "Carron SDSS proxy",
        "arm_candidates": [
            Path("carron_dr17_proxy/carron_proxy_ridges/arm_level_spirality.csv"),
            Path("carron_dr16_proxy/carron_proxy_ridges/arm_level_spirality.csv"),
        ],
    },
    "chen": {
        "label": "Chen SDSS DR12 native",
        "arm_candidates": [
            Path("chen_dr12_native_arms/arm_level_spirality.csv"),
            Path("chen_dr12_native/arm_level_spirality.csv"),
        ],
    },
}


def _parse_edges(text: str) -> np.ndarray:
    vals = [float(x) for x in str(text).replace(";", ",").split(",") if x.strip()]
    if len(vals) < 2:
        raise ValueError("Need at least two z-bin edges")
    return np.asarray(vals, dtype=float)


def _normal_z_one_sided(p: float) -> float:
    return float(norm.isf(float(p))) if np.isfinite(p) and p > 0 else np.inf


def _normal_z_two_sided(p: float) -> float:
    return float(norm.isf(float(p) / 2.0)) if np.isfinite(p) and p > 0 else np.inf


def _p_values_from_null(obs: float, null: np.ndarray, *, signed: bool, positive_defined: bool = False) -> Dict[str, float]:
    vals = np.asarray(null, dtype=float)
    vals = vals[np.isfinite(vals)]
    if len(vals) == 0 or not np.isfinite(obs):
        return {
            "p_two_sided": np.nan,
            "p_one_sided_observed_direction": np.nan,
            "p_one_sided_positive": np.nan,
            "p_one_sided_negative": np.nan,
            "z_two_sided_equiv": np.nan,
            "z_one_sided_equiv": np.nan,
        }
    if positive_defined:
        p_two = (1.0 + np.count_nonzero(vals >= obs)) / (len(vals) + 1.0)
        p_obs = p_two
        p_pos = p_two
        p_neg = np.nan
    elif signed:
        p_two = (1.0 + np.count_nonzero(np.abs(vals) >= abs(obs))) / (len(vals) + 1.0)
        p_pos = (1.0 + np.count_nonzero(vals >= obs)) / (len(vals) + 1.0)
        p_neg = (1.0 + np.count_nonzero(vals <= obs)) / (len(vals) + 1.0)
        p_obs = p_pos if obs >= 0 else p_neg
    else:
        p_two = np.nan
        p_obs = np.nan
        p_pos = np.nan
        p_neg = np.nan
    return {
        "p_two_sided": float(p_two),
        "p_one_sided_observed_direction": float(p_obs),
        "p_one_sided_positive": float(p_pos) if np.isfinite(p_pos) else np.nan,
        "p_one_sided_negative": float(p_neg) if np.isfinite(p_neg) else np.nan,
        "z_two_sided_equiv": _normal_z_two_sided(p_two) if np.isfinite(p_two) else np.nan,
        "z_one_sided_equiv": _normal_z_one_sided(p_obs) if np.isfinite(p_obs) else np.nan,
    }


def _find_arm_path(run_root: Path, catalog: str) -> Optional[Path]:
    for rel in CATALOG_SPECS[catalog]["arm_candidates"]:  # type: ignore[index]
        p = run_root / rel
        if p.exists():
            return p
    return None


def _read_arm_table(path: Path) -> pd.DataFrame:
    d = pd.read_csv(path)
    if "status" in d.columns:
        ok = d["status"].astype(str).str.lower().eq("ok")
        if np.any(ok):
            d = d.loc[ok].copy()
    if "S_tangential" not in d.columns:
        if "mean_t_phi" in d.columns:
            d["S_tangential"] = pd.to_numeric(d["mean_t_phi"], errors="coerce")
        else:
            raise ValueError(f"{path} lacks S_tangential/mean_t_phi")
    if "S_tangential_abs" not in d.columns:
        d["S_tangential_abs"] = np.abs(pd.to_numeric(d["S_tangential"], errors="coerce"))
    if "z_eff" not in d.columns:
        for zc in ["z_mid", "z_center", "z_low", "z"]:
            if zc in d.columns:
                d["z_eff"] = pd.to_numeric(d[zc], errors="coerce")
                break
        if "z_eff" not in d.columns and {"z_low", "z_high"}.issubset(d.columns):
            d["z_eff"] = 0.5 * (pd.to_numeric(d["z_low"], errors="coerce") + pd.to_numeric(d["z_high"], errors="coerce"))
    keep = np.isfinite(pd.to_numeric(d["S_tangential"], errors="coerce")) & np.isfinite(pd.to_numeric(d.get("z_eff", np.nan), errors="coerce"))
    if {"ra", "dec"}.issubset(d.columns):
        keep &= np.isfinite(pd.to_numeric(d["ra"], errors="coerce")) & np.isfinite(pd.to_numeric(d["dec"], errors="coerce"))
    d = d.loc[keep].copy().reset_index(drop=True)
    return d


def _arm_weights(d: pd.DataFrame, mode: str) -> np.ndarray:
    mode = str(mode).lower()
    if mode == "uniform":
        return np.ones(len(d), dtype=float)
    if mode == "n_segments":
        for c in ["n_arm_segments_total", "n_segments_valid", "n_arm_segments_valid", "n_segments"]:
            if c in d.columns:
                v = pd.to_numeric(d[c], errors="coerce").to_numpy(float)
                return np.where(np.isfinite(v) & (v > 0), v, 0.0)
        return np.ones(len(d), dtype=float)
    if mode == "sqrt_points":
        for c in ["n_points_used_total", "n_points_total", "npoints"]:
            if c in d.columns:
                v = pd.to_numeric(d[c], errors="coerce").to_numpy(float)
                return np.sqrt(np.maximum(np.where(np.isfinite(v), v, 0.0), 0.0))
        return np.ones(len(d), dtype=float)
    raise ValueError(f"Unsupported weight mode: {mode}")


def _weighted_mean(vals: np.ndarray, weights: np.ndarray) -> float:
    ok = np.isfinite(vals) & np.isfinite(weights) & (weights > 0)
    if not np.any(ok):
        return np.nan
    return float(np.sum(weights[ok] * vals[ok]) / np.sum(weights[ok]))


def _healpix_blocks(d: pd.DataFrame, nside: int) -> np.ndarray:
    if hp is None:
        if "node_id" in d.columns:
            return pd.factorize(d["node_id"])[0]
        return np.arange(len(d), dtype=int)
    ra = np.deg2rad(pd.to_numeric(d["ra"], errors="coerce").to_numpy(float))
    dec = np.deg2rad(pd.to_numeric(d["dec"], errors="coerce").to_numpy(float))
    theta = 0.5 * np.pi - dec
    phi = ra % (2.0 * np.pi)
    return hp.ang2pix(int(nside), theta, phi, nest=False)


def _projected_null_values(h: np.ndarray, w: np.ndarray, blocks: np.ndarray, *, statistic: str, B: int, rng: np.random.Generator) -> np.ndarray:
    ub, inv = np.unique(blocks, return_inverse=True)
    vals = np.empty(int(B), dtype=float)
    sign_stat = str(statistic).lower().startswith("sign")
    for b in range(int(B)):
        eps = rng.choice(np.array([-1.0, 1.0]), size=len(ub), replace=True)
        hh = h * eps[inv]
        if sign_stat:
            sgn = np.sign(hh)
            good = np.isfinite(sgn) & (sgn != 0.0)
            vals[b] = float(np.mean(sgn[good])) if np.any(good) else np.nan
        else:
            vals[b] = _weighted_mean(hh, w)
    return vals


def _scope_masks(z: np.ndarray, edges: np.ndarray) -> List[Tuple[str, int, float, float, np.ndarray]]:
    rows: List[Tuple[str, int, float, float, np.ndarray]] = [("allz", -1, float(np.nanmin(z)), float(np.nanmax(z)), np.isfinite(z))]
    for ib in range(len(edges) - 1):
        z0, z1 = float(edges[ib]), float(edges[ib + 1])
        if ib == len(edges) - 2:
            m = np.isfinite(z) & (z >= z0) & (z <= z1)
        else:
            m = np.isfinite(z) & (z >= z0) & (z < z1)
        rows.append(("zbin", ib, z0, z1, m))
    return rows


def summarize_projected(run_root: Path, catalog: str, *, edges: np.ndarray, weight_mode: str, B: int, block_nside: int, seed: int) -> List[Dict[str, object]]:
    arm_path = _find_arm_path(run_root, catalog)
    if arm_path is None:
        print(f"[warn] projected: missing arm table for {catalog}")
        return []
    d = _read_arm_table(arm_path)
    if len(d) == 0:
        return []
    h = pd.to_numeric(d["S_tangential"], errors="coerce").to_numpy(float)
    z = pd.to_numeric(d["z_eff"], errors="coerce").to_numpy(float)
    w = _arm_weights(d, weight_mode)
    blocks = _healpix_blocks(d, block_nside) if {"ra", "dec"}.issubset(d.columns) else (pd.factorize(d.get("node_id", pd.Series(np.arange(len(d)))))[0])
    rows: List[Dict[str, object]] = []
    rng0 = np.random.default_rng(int(seed) + 1000 * (list(CATALOG_SPECS).index(catalog) + 1))
    for scope, zbin_id, z0, z1, m0 in _scope_masks(z, edges):
        ok = m0 & np.isfinite(h) & np.isfinite(w) & (w > 0)
        if not np.any(ok):
            continue
        hh, ww, bb = h[ok], w[ok], blocks[ok]
        obs_h = _weighted_mean(hh, ww)
        obs_s = _weighted_mean(np.abs(hh), ww)
        sgn = np.sign(hh)
        sgood = np.isfinite(sgn) & (sgn != 0.0)
        obs_a = float(np.mean(sgn[sgood])) if np.any(sgood) else np.nan
        for statistic, obs, null_kind in [
            ("H_proj", obs_h, "block_signflip"),
            ("A_sign", obs_a, "block_signflip"),
            ("S_proj", obs_s, "not_applicable_for_signflip"),
        ]:
            base = {
                "analysis": "projected",
                "catalog_key": catalog,
                "catalog_label": CATALOG_SPECS[catalog]["label"],
                "scope": scope,
                "zbin_id": int(zbin_id),
                "z_min": float(z0),
                "z_max": float(z1),
                "z_center": float(np.nanmean(z[ok])) if np.any(np.isfinite(z[ok])) else 0.5 * (z0 + z1),
                "statistic": statistic,
                "value": float(obs) if np.isfinite(obs) else np.nan,
                "value_units": "dimensionless",
                "n_arms": int(np.count_nonzero(ok)),
                "weight_mode": weight_mode,
                "null_type": null_kind,
                "null_B": int(B) if null_kind == "block_signflip" else 0,
                "block_nside": int(block_nside) if null_kind == "block_signflip" else np.nan,
            }
            if statistic in {"H_proj", "A_sign"}:
                rng = np.random.default_rng(rng0.integers(0, 2**32 - 1))
                nv = _projected_null_values(hh, ww, bb, statistic=("sign" if statistic == "A_sign" else "H"), B=B, rng=rng)
                base.update(_p_values_from_null(float(obs), nv, signed=True))
                base.update({
                    "null_q16": float(np.nanpercentile(nv, 16)) if np.any(np.isfinite(nv)) else np.nan,
                    "null_q50": float(np.nanpercentile(nv, 50)) if np.any(np.isfinite(nv)) else np.nan,
                    "null_q84": float(np.nanpercentile(nv, 84)) if np.any(np.isfinite(nv)) else np.nan,
                })
            else:
                base.update(_p_values_from_null(np.nan, np.array([], dtype=float), signed=False))
                base["note"] = "S_proj is parity-even; block sign-flip null is unchanged and not a significance test."
            rows.append(base)
    return rows


def _read_csv_optional(path: Path) -> pd.DataFrame:
    return pd.read_csv(path) if path.exists() else pd.DataFrame()


def summarize_extrinsic(run_root: Path, catalog: str, *, null_mode: str = "block") -> List[Dict[str, object]]:
    edir = run_root / "extrinsic_spirality"
    best = _read_csv_optional(edir / f"{catalog}_extrinsic_bestfit.csv")
    zb = _read_csv_optional(edir / f"{catalog}_extrinsic_zbins.csv")
    null = _read_csv_optional(edir / f"{catalog}_extrinsic_lookelsewhere_signflip_{null_mode}_null.csv")
    summ = _read_csv_optional(edir / f"{catalog}_extrinsic_lookelsewhere_signflip_{null_mode}_summary.csv")
    rows: List[Dict[str, object]] = []
    if len(best) == 0 and len(zb) == 0:
        print(f"[warn] extrinsic: missing products for {catalog} under {edir}")
        return rows

    # Total dipole amplitude.
    if len(best):
        b = best.iloc[0]
        obs = float(pd.to_numeric(pd.Series([b.get("A_dip", b.get("H_ext", np.nan))]), errors="coerce").iloc[0])
        row = {
            "analysis": "extrinsic",
            "catalog_key": catalog,
            "catalog_label": CATALOG_SPECS.get(catalog, {}).get("label", catalog),
            "scope": "allz",
            "zbin_id": -1,
            "z_min": np.nan,
            "z_max": np.nan,
            "z_center": np.nan,
            "statistic": "H_ext",
            "value": obs,
            "value_units": "dimensionless",
            "n_arms": int(b.get("n_arms", -1)) if np.isfinite(pd.to_numeric(pd.Series([b.get("n_arms", np.nan)]), errors="coerce").iloc[0]) else -1,
            "weight_mode": "n_segments",
            "null_type": f"lookelsewhere_signflip_{null_mode}",
            "null_B": int(summ.iloc[0].get("null_B", len(null))) if len(summ) else len(null),
            "block_nside": int(summ.iloc[0].get("block_nside", np.nan)) if len(summ) and np.isfinite(summ.iloc[0].get("block_nside", np.nan)) else np.nan,
        }
        if len(summ) and "p_global_lookelsewhere" in summ.columns:
            p = float(summ.iloc[0]["p_global_lookelsewhere"])
            row.update({
                "p_two_sided": p,
                "p_one_sided_observed_direction": p,
                "p_one_sided_positive": p,
                "p_one_sided_negative": np.nan,
                "z_two_sided_equiv": _normal_z_two_sided(p),
                "z_one_sided_equiv": _normal_z_one_sided(p),
            })
        elif len(null) and "max_abs_H_ext" in null.columns:
            row.update(_p_values_from_null(obs, pd.to_numeric(null["max_abs_H_ext"], errors="coerce").to_numpy(float), signed=False, positive_defined=True))
        rows.append(row)

        # Total sign asymmetry on the dipole-selected axis.
        obs_s = float(pd.to_numeric(pd.Series([b.get("sign_asym_ext_percent", np.nan)]), errors="coerce").iloc[0])
        row_s = dict(row)
        row_s.update({"statistic": "A_sign_ext_percent", "value": obs_s, "value_units": "percent"})
        if len(null):
            # The plotted extrinsic sign statistic is evaluated on the same H-selected axis.
            # Use the at-max-H null when available; otherwise fall back to max absolute sign.
            col = "abs_sign_asym_ext_percent_at_max_H" if "abs_sign_asym_ext_percent_at_max_H" in null.columns else "max_abs_sign_asym_ext_percent"
            row_s.update(_p_values_from_null(abs(obs_s), pd.to_numeric(null[col], errors="coerce").to_numpy(float), signed=False, positive_defined=True))
        else:
            row_s.update(_p_values_from_null(np.nan, np.array([], dtype=float), signed=False))
        rows.append(row_s)

    # Per-bin values.  The extrinsic driver already adds per-bin H and sign p-values
    # when the sign-flip null was requested; recompute/fill from the null CSV if needed.
    if len(zb):
        for _, r in zb.iterrows():
            ib = int(r.get("zbin_id", -1))
            for statistic, val_col, unit, null_col in [
                ("H_ext", "H_ext", "dimensionless", f"H_ext_zbin_{ib}"),
                ("A_sign_ext_percent", "sign_asym_ext_percent", "percent", f"sign_asym_ext_percent_zbin_{ib}"),
            ]:
                obs = float(pd.to_numeric(pd.Series([r.get(val_col, np.nan)]), errors="coerce").iloc[0])
                out = {
                    "analysis": "extrinsic",
                    "catalog_key": catalog,
                    "catalog_label": CATALOG_SPECS.get(catalog, {}).get("label", catalog),
                    "scope": "zbin",
                    "zbin_id": ib,
                    "z_min": float(r.get("z_min", np.nan)),
                    "z_max": float(r.get("z_max", np.nan)),
                    "z_center": float(r.get("z_center", np.nan)),
                    "statistic": statistic,
                    "value": obs,
                    "value_units": unit,
                    "n_arms": int(r.get("n_arms", -1)) if np.isfinite(pd.to_numeric(pd.Series([r.get("n_arms", np.nan)]), errors="coerce").iloc[0]) else -1,
                    "weight_mode": "n_segments",
                    "null_type": f"lookelsewhere_signflip_{null_mode}",
                    "null_B": len(null),
                    "block_nside": np.nan,
                }
                if statistic == "H_ext" and "p_global_lookelsewhere" in r.index and np.isfinite(r.get("p_global_lookelsewhere", np.nan)):
                    p = float(r["p_global_lookelsewhere"])
                    out.update({
                        "p_two_sided": p,
                        "p_one_sided_observed_direction": p,
                        "p_one_sided_positive": p,
                        "p_one_sided_negative": np.nan,
                        "z_two_sided_equiv": _normal_z_two_sided(p),
                        "z_one_sided_equiv": _normal_z_one_sided(p),
                    })
                elif statistic == "A_sign_ext_percent" and "p_sign_asym_global_lookelsewhere" in r.index and np.isfinite(r.get("p_sign_asym_global_lookelsewhere", np.nan)):
                    p = float(r["p_sign_asym_global_lookelsewhere"])
                    out.update({
                        "p_two_sided": p,
                        "p_one_sided_observed_direction": p,
                        "p_one_sided_positive": p,
                        "p_one_sided_negative": np.nan,
                        "z_two_sided_equiv": _normal_z_two_sided(p),
                        "z_one_sided_equiv": _normal_z_one_sided(p),
                    })
                elif len(null) and null_col in null.columns:
                    nv = np.abs(pd.to_numeric(null[null_col], errors="coerce").to_numpy(float))
                    out.update(_p_values_from_null(abs(obs), nv, signed=False, positive_defined=True))
                else:
                    out.update(_p_values_from_null(np.nan, np.array([], dtype=float), signed=False))
                rows.append(out)
    return rows


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--run-root", required=True, help="Completed run directory.")
    p.add_argument("--outdir", default=None, help="Default: <run-root>/paper_tables")
    p.add_argument("--catalogs", nargs="+", default=["sconce", "carron", "chen"], choices=list(CATALOG_SPECS))
    p.add_argument("--zbin-edges", default="0.1,0.225,0.35,0.475,0.6")
    p.add_argument("--projected-null-B", type=int, default=1000)
    p.add_argument("--projected-block-nside", type=int, default=16)
    p.add_argument("--projected-weight-mode", default="n_segments", choices=["uniform", "n_segments", "sqrt_points"])
    p.add_argument("--extrinsic-null-mode", default="block")
    p.add_argument("--seed", type=int, default=20260711)
    args = p.parse_args()

    run_root = Path(args.run_root).expanduser().resolve()
    outdir = Path(args.outdir).expanduser().resolve() if args.outdir else run_root / "paper_tables"
    outdir.mkdir(parents=True, exist_ok=True)
    edges = _parse_edges(args.zbin_edges)

    projected_rows: List[Dict[str, object]] = []
    extrinsic_rows: List[Dict[str, object]] = []
    for cat in args.catalogs:
        projected_rows.extend(summarize_projected(
            run_root, cat, edges=edges, weight_mode=args.projected_weight_mode,
            B=int(args.projected_null_B), block_nside=int(args.projected_block_nside), seed=int(args.seed),
        ))
        extrinsic_rows.extend(summarize_extrinsic(run_root, cat, null_mode=str(args.extrinsic_null_mode)))

    proj = pd.DataFrame(projected_rows)
    ext = pd.DataFrame(extrinsic_rows)
    allsig = pd.concat([proj, ext], ignore_index=True) if len(proj) or len(ext) else pd.DataFrame()

    proj_path = outdir / "projected_significance_summary.csv"
    ext_path = outdir / "extrinsic_significance_summary.csv"
    all_path = outdir / "main_significance_summary.csv"
    proj.to_csv(proj_path, index=False)
    ext.to_csv(ext_path, index=False)
    allsig.to_csv(all_path, index=False)
    print("[write]", proj_path)
    print("[write]", ext_path)
    print("[write]", all_path)


if __name__ == "__main__":
    main()
