def ellipse_lonlat(ra0: float, dec0: float, cov: np.ndarray, nsig: float, n: int = 240) -> tuple[np.ndarray, np.ndarray]:
    vals, vecs = np.linalg.eigh(cov)
    vals = np.maximum(vals, 0.0)
    t = np.linspace(0, 2*np.pi, n)
    circle = np.vstack([np.cos(t), np.sin(t)])
    # 2D Gaussian 68.3% and 95.4% contour scales.
    scale = {1.0: np.sqrt(2.30), 2.0: np.sqrt(6.17)}.get(float(nsig), float(nsig))
    xy = vecs @ (np.sqrt(vals)[:, None] * scale * circle)
    dra = xy[0] / max(1e-6, np.cos(np.deg2rad(dec0)))
    ra = (ra0 + dra) % 360.0
    dec = np.clip(dec0 + xy[1], -90, 90)
    return ra, dec


def canonical_halfsky_mask(
    nside: int,
    *,
    mode: str = "nearest_best",
    ref_ra_deg: float | None = None,
    ref_dec_deg: float | None = None,
) -> np.ndarray:
    require_healpy()
    npix = hp.nside2npix(int(nside))
    pix = np.arange(npix)
    theta, phi = hp.pix2ang(int(nside), pix, nest=False)
    ra = np.rad2deg(phi) % 360.0
    dec = 90.0 - np.rad2deg(theta)
    if mode in {"nearest_best", "nearest_ref", "bestfit"}:
        if ref_ra_deg is None or ref_dec_deg is None:
            return ra >= 180.0
        v = unit_xyz_from_radec(ra, dec)
        ref = unit_xyz_from_radec(np.array([float(ref_ra_deg)]), np.array([float(ref_dec_deg)]))[0]
        return (v @ ref) >= 0.0
    if mode == "ra_ge_180":
        return ra >= 180.0
    if mode == "none":
        return np.ones(npix, dtype=bool)
    raise ValueError(f"Unknown axis display mode: {mode}")


def bootstrap_axis_density_map(
    boot: pd.DataFrame,
    *,
    nside: int,
    smooth_fwhm_deg: float,
    axis_display_mode: str,
    ref_ra_deg: float | None = None,
    ref_dec_deg: float | None = None,
) -> tuple[np.ndarray, np.ndarray, np.ndarray, pd.DataFrame]:
    """Return a normalized bootstrap-density map over the canonical axial sky."""
    require_healpy()
    npix = hp.nside2npix(int(nside))
    counts = np.zeros(npix, dtype=float)

    ra_b, dec_b = canonicalize_axis_radec(
        boot["ra_deg"].to_numpy(float),
        boot["dec_deg"].to_numpy(float),
        mode=axis_display_mode,
        ref_ra_deg=ref_ra_deg,
        ref_dec_deg=ref_dec_deg,
    )
    theta = np.deg2rad(90.0 - dec_b)
    phi = np.deg2rad(ra_b % 360.0)
    pix = hp.ang2pix(int(nside), theta, phi, nest=False)
    np.add.at(counts, pix, 1.0)

    density = counts.copy()
    if float(smooth_fwhm_deg) > 0.0 and np.sum(density) > 0:
        density = hp.smoothing(density, fwhm=np.deg2rad(float(smooth_fwhm_deg)))
        density = np.where(np.isfinite(density) & (density > 0), density, 0.0)

    mask = canonical_halfsky_mask(nside, mode=axis_display_mode, ref_ra_deg=ref_ra_deg, ref_dec_deg=ref_dec_deg)
    density[~mask] = 0.0
    total = float(np.sum(density[mask]))
    prob = density / total if total > 0 else density

    boot_disp = boot.copy()
    boot_disp["ra_deg_display"] = ra_b
    boot_disp["dec_deg_display"] = dec_b
    return prob, mask, pix, boot_disp


def hpd_threshold_and_fraction(
    prob: np.ndarray,
    mask: np.ndarray,
    *,
    level: float,
    nside: int,
) -> dict:
    """Highest-posterior-density threshold and sky fraction for one level."""
    vals = np.asarray(prob[mask], dtype=float)
    vals = vals[np.isfinite(vals)]
    vals = vals[vals > 0]
    if len(vals) == 0:
        return {
            "level": float(level),
            "threshold": np.nan,
            "n_pix": 0,
            "area_deg2": np.nan,
            "f_sky_axial": np.nan,
            "f_sky_full_if_antipodal": np.nan,
        }

    order = np.sort(vals)[::-1]
    csum = np.cumsum(order)
    csum /= csum[-1]
    idx = int(np.searchsorted(csum, float(level), side="left"))
    idx = min(idx, len(order) - 1)
    thr = float(order[idx])
    region = mask & np.isfinite(prob) & (prob >= thr)
    nreg = int(np.count_nonzero(region))
    nmask = int(np.count_nonzero(mask))
    pix_area_deg2 = float(hp.nside2pixarea(int(nside), degrees=True))
    area_deg2 = nreg * pix_area_deg2
    f_axial = nreg / nmask if nmask > 0 else np.nan
    f_full = (2.0 * area_deg2) / (4.0 * np.pi * DEG * DEG)
    return {
        "level": float(level),
        "threshold": thr,
        "n_pix": nreg,
        "area_deg2": area_deg2,
        "f_sky_axial": float(f_axial),
        "f_sky_full_if_antipodal": float(f_full),
    }


def contour_summary_for_bootstrap(
    boot: pd.DataFrame,
    *,
    catalog_key: str,
    catalog_label: str,
    nside: int,
    smooth_fwhm_deg: float,
    axis_display_mode: str,
    ref_ra_deg: float | None = None,
    ref_dec_deg: float | None = None,
    levels: tuple[float, float] = (0.6827, 0.9545),
) -> tuple[np.ndarray, np.ndarray, pd.DataFrame, pd.DataFrame]:
    prob, mask, pix, boot_disp = bootstrap_axis_density_map(
        boot,
        nside=nside,
        smooth_fwhm_deg=smooth_fwhm_deg,
        axis_display_mode=axis_display_mode,
        ref_ra_deg=ref_ra_deg,
        ref_dec_deg=ref_dec_deg,
    )
    rows = []
    for lev in levels:
        row = hpd_threshold_and_fraction(prob, mask, level=lev, nside=nside)
        row.update({
            "catalog_key": catalog_key,
            "catalog_label": catalog_label,
            "nside": int(nside),
            "smooth_fwhm_deg": float(smooth_fwhm_deg),
            "axis_display_mode": str(axis_display_mode),
        })
        rows.append(row)
    return prob, mask, pd.DataFrame(rows), boot_disp


def _boundary_pixels(region: np.ndarray, *, nside: int) -> np.ndarray:
    """Return pixels in region that have at least one neighbour outside region."""
    pix = np.flatnonzero(region)
    if len(pix) == 0:
        return pix
    neigh = hp.get_all_neighbours(int(nside), pix, nest=False)
    # neighbours has shape (8, N), with -1 possible at boundaries.
    safe_neigh = np.clip(neigh, 0, len(region) - 1)
    outside = np.any((neigh < 0) | (~region[safe_neigh]), axis=0)
    return pix[outside]


def _split_polyline_on_ra_wrap(lon: np.ndarray, lat: np.ndarray) -> list[tuple[np.ndarray, np.ndarray]]:
    """Split a lon/lat polyline where longitude jumps across the 0/360 seam."""
    lon = np.asarray(lon, dtype=float)
    lat = np.asarray(lat, dtype=float)
    if len(lon) <= 1:
        return [(lon, lat)]
    jumps = np.where(np.abs(np.diff(lon)) > 180.0)[0]
    if len(jumps) == 0:
        return [(lon, lat)]
    parts = []
    start = 0
    for j in jumps:
        if j + 1 - start >= 2:
            parts.append((lon[start:j+1], lat[start:j+1]))
        start = j + 1
    if len(lon) - start >= 2:
        parts.append((lon[start:], lat[start:]))
    return parts


def _plot_pixel_boundaries(nside: int, pix: np.ndarray, *, color: str, linestyle: str, linewidth: float, step: int = 2) -> None:
    """Draw HEALPix pixel boundaries using projplot; works without hp.projcontour."""
    for p in np.asarray(pix, dtype=int):
        xyz = hp.boundaries(int(nside), int(p), step=int(step), nest=False)
        x, y, z = xyz
        lon = (np.rad2deg(np.arctan2(y, x)) + 360.0) % 360.0
        lat = np.rad2deg(np.arcsin(np.clip(z, -1.0, 1.0)))
        # Close each boundary polygon.
        lon = np.r_[lon, lon[0]]
        lat = np.r_[lat, lat[0]]
        for lo, la in _split_polyline_on_ra_wrap(lon, lat):
            hp.projplot(lo, la, lonlat=True, color=color, linestyle=linestyle, linewidth=linewidth, alpha=0.95)


def draw_hpd_contours(
    prob: np.ndarray,
    mask: np.ndarray,
    summary: pd.DataFrame,
    *,
    color: str,
) -> None:
    """Draw HPD contour boundaries without relying on hp.projcontour.

    Some installed healpy versions do not expose projcontour.  We therefore
    threshold the smoothed bootstrap-density map, identify boundary HEALPix
    pixels, and draw their pixel boundaries.  The smoothness is controlled by
    the map NSIDE and by --axis-contour-smooth-fwhm-deg.
    """
    require_healpy()
    nside = hp.npix2nside(len(prob))

    # Draw 95 percent first, then 68 percent on top.
    for lev, ls, lw in [(0.9545, "--", 1.6), (0.6827, "-", 2.1)]:
        sub = summary[np.isclose(summary["level"].to_numpy(float), lev, rtol=0, atol=1e-4)]
        if len(sub) == 0:
            continue
        thr = float(sub.iloc[0]["threshold"])
        if not np.isfinite(thr):
            continue
        region = mask & np.isfinite(prob) & (prob >= thr)
        bpix = _boundary_pixels(region, nside=nside)
        _plot_pixel_boundaries(nside, bpix, color=color, linestyle=ls, linewidth=lw, step=2)


def _wrap_for_plot(ra: np.ndarray) -> np.ndarray:
    return np.asarray(ra, dtype=float) % 360.0


def _split_on_wrap(ra: np.ndarray, dec: np.ndarray) -> list[tuple[np.ndarray, np.ndarray]]:
    ra_plot = _wrap_for_plot(ra)
    dec = np.asarray(dec, dtype=float)
    jumps = np.where(np.abs(np.diff(ra_plot)) > 180.0)[0]
    parts: list[tuple[np.ndarray, np.ndarray]] = []
    start = 0
    for j in jumps:
        if j + 1 - start >= 2:
            parts.append((ra_plot[start:j+1], dec[start:j+1]))
        start = j + 1
    if len(ra_plot) - start >= 2:
        parts.append((ra_plot[start:], dec[start:]))
    return parts


def _local_xy_for_kde(ra: np.ndarray, dec: np.ndarray, ra0: float, dec0: float) -> tuple[np.ndarray, np.ndarray]:
    x = (np.asarray(ra, dtype=float) - float(ra0)) * np.cos(np.deg2rad(float(dec0)))
    y = np.asarray(dec, dtype=float) - float(dec0)
    return x, y


def _lonlat_from_kde_xy(x: np.ndarray, y: np.ndarray, ra0: float, dec0: float) -> tuple[np.ndarray, np.ndarray]:
    ra = float(ra0) + np.asarray(x, dtype=float) / max(1e-8, np.cos(np.deg2rad(float(dec0))))
    dec = float(dec0) + np.asarray(y, dtype=float)
    return ra, np.clip(dec, -90.0, 90.0)


def _kde_grid_from_points(x: np.ndarray, y: np.ndarray, *, pad_deg: float = 10.0, grid_size: int = 280) -> tuple[np.ndarray, np.ndarray]:
    xmin, xmax = np.nanpercentile(x, [0.5, 99.5])
    ymin, ymax = np.nanpercentile(y, [0.5, 99.5])
    xmin -= pad_deg
    xmax += pad_deg
    ymin -= pad_deg
    ymax += pad_deg
    xx = np.linspace(xmin, xmax, int(grid_size))
    yy = np.linspace(ymin, ymax, int(grid_size))
    return np.meshgrid(xx, yy)


def _contour_segments_from_matplotlib(X: np.ndarray, Y: np.ndarray, Z: np.ndarray, level: float) -> list[np.ndarray]:
    """Return contour segments robustly across Matplotlib versions."""
    fig_tmp, ax_tmp = plt.subplots()
    cs = ax_tmp.contour(X, Y, Z, levels=[float(level)])
    segs: list[np.ndarray] = []
    if hasattr(cs, "allsegs"):
        for seg in cs.allsegs[0]:
            if len(seg) >= 2:
                segs.append(np.asarray(seg, dtype=float).copy())
    elif hasattr(cs, "collections"):
        for coll in cs.collections:
            for path in coll.get_paths():
                vv = np.asarray(path.vertices, dtype=float)
                if len(vv) >= 2:
                    segs.append(vv.copy())
    plt.close(fig_tmp)
    return segs


def _kde_density_and_hpd(
    boot: pd.DataFrame,
    best: dict,
    *,
    axis_display_mode: str,
    kde_bw_scale: float = 1.0,
    area_nside: int = 128,
    grid_size: int = 280,
    grid_pad_deg: float = 10.0,
) -> tuple[np.ndarray, np.ndarray, np.ndarray, float, float, dict[float, float], pd.DataFrame, pd.DataFrame]:
    """Build tangent-plane KDE and HPD thresholds for an axial bootstrap cloud."""
    from scipy.stats import gaussian_kde

    ref_ra = float(best["ra_deg"])
    ref_dec = float(best["dec_deg"])
    ra_b, dec_b = canonicalize_axis_radec(
        boot["ra_deg"].to_numpy(float),
        boot["dec_deg"].to_numpy(float),
        mode=axis_display_mode,
        ref_ra_deg=ref_ra,
        ref_dec_deg=ref_dec,
    )

    ra0 = float(np.nanmedian(ra_b))
    ra_un = unwrap_ra_about(ra_b, ra0)
    ra0 = float(np.nanmedian(ra_un))
    dec0 = float(np.nanmedian(dec_b))

    x, y = _local_xy_for_kde(ra_un, dec_b, ra0, dec0)
    kde = gaussian_kde(np.vstack([x, y]), bw_method="scott")
    kde.set_bandwidth(kde.factor * float(kde_bw_scale))

    X, Y = _kde_grid_from_points(x, y, pad_deg=grid_pad_deg, grid_size=grid_size)
    Z = kde(np.vstack([X.ravel(), Y.ravel()])).reshape(X.shape)

    # Estimate HPD thresholds and sky fractions on the canonical axial half-sky.
    npix = hp.nside2npix(int(area_nside))
    pix = np.arange(npix)
    theta, phi = hp.pix2ang(int(area_nside), pix, nest=False)
    ra = np.rad2deg(phi) % 360.0
    dec = 90.0 - np.rad2deg(theta)
    v = unit_xyz_from_radec(ra, dec)
    ref = unit_xyz_from_radec(np.array([ref_ra]), np.array([ref_dec]))[0]
    mask = (v @ ref) >= 0.0
    ra_c, dec_c = canonicalize_axis_radec(
        ra[mask], dec[mask],
        mode=axis_display_mode,
        ref_ra_deg=ref_ra,
        ref_dec_deg=ref_dec,
    )
    ra_c_un = unwrap_ra_about(ra_c, ra0)
    xa, ya = _local_xy_for_kde(ra_c_un, dec_c, ra0, dec0)
    dens = kde(np.vstack([xa, ya]))
    dens = np.where(np.isfinite(dens) & (dens > 0), dens, 0.0)

    order = np.argsort(dens)[::-1]
    ds = dens[order]
    cs = np.cumsum(ds)
    cs /= cs[-1] if cs[-1] > 0 else 1.0
    thresholds: dict[float, float] = {}
    rows = []
    pix_area_deg2 = float(hp.nside2pixarea(int(area_nside), degrees=True))
    for lev in [0.6827, 0.9545]:
        idx = int(np.searchsorted(cs, float(lev), side="left"))
        idx = min(idx, len(ds) - 1)
        thr = float(ds[idx])
        thresholds[float(lev)] = thr
        nreg = int(np.count_nonzero(dens >= thr))
        nmask = int(len(dens))
        area_deg2 = nreg * pix_area_deg2
        rows.append({
            "level": float(lev),
            "threshold": thr,
            "n_pix_area_grid": nreg,
            "n_pix_domain": nmask,
            "area_deg2": area_deg2,
            "f_sky_axial_domain": nreg / nmask if nmask > 0 else np.nan,
            "f_sky_full_if_antipodal": (2.0 * area_deg2) / (4.0 * np.pi * DEG * DEG),
            "area_nside": int(area_nside),
            "kde_bw_scale": float(kde_bw_scale),
            "axis_display_mode": str(axis_display_mode),
        })

    boot_disp = boot.copy()
    boot_disp["ra_deg_display"] = ra_b
    boot_disp["dec_deg_display"] = dec_b
    boot_disp["ra_deg_unwrapped_about_kde_center"] = ra_un
    summary = pd.DataFrame(rows)
    return X, Y, Z, ra0, dec0, thresholds, summary, boot_disp


def _draw_kde_contours_on_healpy(
    *,
    X: np.ndarray,
    Y: np.ndarray,
    Z: np.ndarray,
    thresholds: dict[float, float],
    ra0: float,
    dec0: float,
    color: str,
) -> None:
    for lev, ls, lw in [(0.9545, "--", 1.8), (0.6827, "-", 2.3)]:
        if lev not in thresholds:
            continue
        for seg in _contour_segments_from_matplotlib(X, Y, Z, thresholds[lev]):
            ra_line, dec_line = _lonlat_from_kde_xy(seg[:, 0], seg[:, 1], ra0, dec0)
            for rp, dp in _split_on_wrap(ra_line, dec_line):
                hp.projplot(rp, dp, lonlat=True, color=color, linestyle=ls, linewidth=lw)


