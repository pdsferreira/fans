def _axis_legend_value_error_columns(best: dict, error_source: str = "objective") -> tuple[str, str]:
    """Amplitude/error columns for a global-axis angular CI in the legend."""
    source = str(error_source).lower().strip()
    objective = str(best.get("axis_objective", "dipole")).lower().strip()
    if source in {"dipole", "h", "h_ext", "a_dip"}:
        return "H_ext", "H_ext_err"
    if source in {"axial_sign", "sign", "sign_asym", "sign_asymmetry"}:
        return "sign_asym_ext_percent", "sign_asym_ext_percent_err"
    if source in {"objective", "auto"}:
        if objective in {"axial_sign", "sign", "sign_asym", "sign_asymmetry"}:
            return "sign_asym_ext_percent", "sign_asym_ext_percent_err"
        return "H_ext", "H_ext_err"
    raise ValueError(f"Unknown axis legend error source: {error_source!r}")


def _format_axis_arctan95ci_line(label: str, best: dict, *, error_source: str = "objective") -> str:
    """Format one global axis with RA/Dec 95% CI estimated from atan(sigma_A/A).

    The Planck-like ``atan(sigma_A/A)`` estimate gives an *angular radius* on
    the sphere, not independent RA and Dec errors.  For a compact legend we
    convert this angular 95% radius to approximate coordinate half-widths using

        Delta Dec_95 ~= theta_95,
        Delta RA_95  ~= theta_95 / cos(Dec),

    capped at 180 deg because RA is effectively unconstrained inside a cone that
    reaches a pole.  The string is plain Unicode text (no mathtext) to avoid
    Matplotlib parsing issues in figure legends.
    """
    short = short_catalog_label(label)
    ra = _safe_float_from_mapping(best, "ra_deg_display", _safe_float_from_mapping(best, "ra_deg"))
    dec = _safe_float_from_mapping(best, "dec_deg_display", _safe_float_from_mapping(best, "dec_deg"))
    if not np.isfinite(ra) or not np.isfinite(dec):
        return f"{short}: axis unavailable"
    val_col, err_col = _axis_legend_value_error_columns(best, error_source=error_source)
    amp = abs(_safe_float_from_mapping(best, val_col, np.nan))
    err = abs(_safe_float_from_mapping(best, err_col, np.nan))
    if np.isfinite(amp) and amp > 0 and np.isfinite(err) and err > 0:
        theta95 = float(min(90.0, 2.0 * np.rad2deg(np.arctan2(err, max(amp, 1e-15)))))
        dec95 = theta95
        cosd = abs(float(np.cos(np.deg2rad(dec))))
        if cosd < 1e-3:
            ra95 = 180.0
        else:
            ra95 = float(min(180.0, theta95 / cosd))
        return f"{short}: RA={ra:.0f}°±{ra95:.0f}°, Dec={dec:.0f}°±{dec95:.0f}°"
    # Fall back to the bootstrap RA/Dec formatting if no amplitude error exists.
    return _format_axis_95ci_line(label, best)


def _scalar_asin_deg(v: float) -> float:
    """asin(v) in degrees for scalar values, with clipping and NaN support."""
    try:
        vv = float(v)
    except Exception:
        return np.nan
    if not np.isfinite(vv):
        return np.nan
    return float(np.rad2deg(np.arcsin(vv))) if abs(vv) <= 1.0 else np.nan


def _scalar_asin_err_deg(value: float, err: float) -> float:
    """Symmetric asin-propagated error in degrees for scalar values."""
    try:
        v = float(value)
        e = abs(float(err))
    except Exception:
        return np.nan
    if not (np.isfinite(v) and np.isfinite(e)):
        return np.nan
    lo = _scalar_asin_deg(v - e)
    hi = _scalar_asin_deg(v + e)
    if not (np.isfinite(lo) and np.isfinite(hi)):
        return np.nan
    return float(0.5 * (hi - lo))


def _cluster_bootstrap_stat(values, weights, clusters, *, statistic: str, B: int = 1000, seed: int = 314159) -> float:
    """Return a bootstrap 1-sigma error for a full-range scalar statistic.

    The caller supplies spatial-block labels. It is a fallback for legacy
    products; v88 plots read the already saved joint spatial draws instead.
    """
    v = np.asarray(values, dtype=float)
    w = np.asarray(weights, dtype=float) if weights is not None else np.ones_like(v)
    ok = np.isfinite(v) & np.isfinite(w) & (w > 0)
    if str(statistic).lower().startswith("sign"):
        ok &= (v != 0)
    v, w = v[ok], w[ok]
    if clusters is None:
        cl = np.arange(len(v))
    else:
        cl = np.asarray(clusters)[ok]
    if len(v) < 2:
        return np.nan
    ucl, inv = np.unique(cl, return_inverse=True)
    if len(ucl) < 2:
        return np.nan
    rng = np.random.default_rng(int(seed))
    vals = []
    for _ in range(int(B)):
        take = rng.integers(0, len(ucl), size=len(ucl))
        cnt = np.bincount(take, minlength=len(ucl)).astype(float)
        mult = cnt[inv]
        ww = w * mult
        if not np.any(ww > 0):
            continue
        if str(statistic).lower().startswith("sign"):
            vals.append(100.0 * float(np.average(np.sign(v), weights=ww)))
        elif str(statistic).lower().startswith("abs") or str(statistic).lower().startswith("spir"):
            vals.append(float(np.average(np.abs(v), weights=ww)))
        else:
            vals.append(float(np.average(v, weights=ww)))
    vals = np.asarray(vals, dtype=float)
    vals = vals[np.isfinite(vals)]
    if len(vals) < 5:
        return np.nan
    return float(0.5 * (np.nanpercentile(vals, 84) - np.nanpercentile(vals, 16)))


def _projected_fullrange_totals_by_catalog(
    projected: list[tuple[str, str, pd.DataFrame]],
    *,
    angle: bool,
    B_null: int = 1000,
    B_boot: int = 1000,
    block_nside: int = 16,
    seed: int = 20260719,
) -> dict[str, dict[str, dict[str, float]]]:
    """Full-range projected values, 1-sigma bootstrap errors and sign-flip nulls.

    Returns values in the same plotting units as the panel: H and spirality are
    converted to asin-degrees when ``angle=True``; sign asymmetry is always in %.
    For spirality, the block sign-flip null is not defined because |S_phi| is
    parity-even, so the mock thresholds are NaN by design.
    """
    out: dict[str, dict[str, dict[str, float]]] = {}
    try:
        from . import pipeline as _pipe
    except Exception as exc:
        print(f"[warn] projected full-range totals unavailable: {exc!r}")
        return out

    for key, label, summ in projected:
        k = str(key).lower()
        out[k] = {}
        try:
            if summ is None or len(summ) == 0:
                continue
            tab_path, weight_mode = _pipe._infer_measurement_table_and_weight(summ)
            if tab_path is None or not Path(tab_path).exists():
                continue
            if weight_mode == "n_segments":
                from spirality.revision_plot_data import find_revision_output, fullrange_markers
                revised = find_revision_output(tab_path, k)
                if revised is not None:
                    out[k] = fullrange_markers(revised, angle=angle)
                    continue
            d = _pipe.normalise_measurement_columns(pd.read_csv(tab_path))
            if "status" in d.columns:
                st = d["status"].astype(str).str.lower()
                keep = st.eq("ok")
                d = d.loc[keep].copy()
            if "S_tangential" not in d.columns or len(d) == 0:
                continue
            z = _pipe.robust_z_center(d)
            z0 = float(np.nanmin(pd.to_numeric(summ.get("z_min"), errors="coerce"))) if "z_min" in summ.columns else np.nan
            z1 = float(np.nanmax(pd.to_numeric(summ.get("z_max"), errors="coerce"))) if "z_max" in summ.columns else np.nan
            mask = np.isfinite(z)
            if np.isfinite(z0):
                mask &= z >= z0
            if np.isfinite(z1):
                mask &= z <= z1
            d = d.loc[mask].copy().reset_index(drop=True)
            if len(d) == 0:
                continue
            h = pd.to_numeric(d["S_tangential"], errors="coerce").to_numpy(float)
            w = _pipe.summary_weights(d, weight_mode)
            ok = np.isfinite(h) & np.isfinite(w) & (w > 0)
            if not np.any(ok):
                continue
            h = h[ok]
            w = w[ok]
            dd = d.loc[ok].copy().reset_index(drop=True)
            clusters = _pipe.assign_healpix_blocks(dd, int(block_nside))

            # Observed full-range projected quantities.
            H = float(np.average(h, weights=w))
            Serr = _cluster_bootstrap_stat(h, w, clusters, statistic="abs", B=B_boot, seed=int(seed) + 19)
            Herr = _cluster_bootstrap_stat(h, w, clusters, statistic="H", B=B_boot, seed=int(seed) + 23)
            sign_mask = h != 0
            if np.any(sign_mask):
                A = 100.0 * float(np.average(np.sign(h[sign_mask])))
                Aerr = _cluster_bootstrap_stat(h[sign_mask], np.ones(np.count_nonzero(sign_mask)), np.asarray(clusters)[sign_mask], statistic="sign", B=B_boot, seed=int(seed) + 29)
            else:
                A, Aerr = np.nan, np.nan
            S = float(np.average(np.abs(h), weights=w))

            # Block sign-flip full-range nulls for H and sign asymmetry.
            blocks = _pipe.assign_healpix_blocks(dd, int(block_nside))
            ub, inv = np.unique(blocks, return_inverse=True)
            rng = np.random.default_rng(int(seed) + _pipe._catalog_seed_offset(str(key)))
            null_H = np.empty(int(B_null), dtype=float)
            null_A = np.empty(int(B_null), dtype=float)
            for ib in range(int(B_null)):
                eps = rng.choice(np.array([-1.0, 1.0]), size=len(ub), replace=True)
                hh = h * eps[inv]
                null_H[ib] = abs(float(np.average(hh, weights=w)))
                nz = hh != 0
                null_A[ib] = abs(100.0 * float(np.average(np.sign(hh[nz])))) if np.any(nz) else np.nan
            null_H = null_H[np.isfinite(null_H)]
            null_A = null_A[np.isfinite(null_A)]
            H_q68 = float(np.nanpercentile(null_H, SIGNED_ABS_1SIGMA_PCT)) if len(null_H) else np.nan
            H_q95 = float(np.nanpercentile(null_H, SIGNED_ABS_2SIGMA_PCT)) if len(null_H) else np.nan
            A_q68 = float(np.nanpercentile(null_A, SIGNED_ABS_1SIGMA_PCT)) if len(null_A) else np.nan
            A_q95 = float(np.nanpercentile(null_A, SIGNED_ABS_2SIGMA_PCT)) if len(null_A) else np.nan

            if angle:
                H_plot = _scalar_asin_deg(H)
                Herr_plot = _scalar_asin_err_deg(H, Herr)
                S_plot = _scalar_asin_deg(S)
                Serr_plot = _scalar_asin_err_deg(S, Serr)
                H_q68_plot = _scalar_asin_deg(H_q68)
                H_q95_plot = _scalar_asin_deg(H_q95)
            else:
                H_plot, Herr_plot, S_plot, Serr_plot = H, Herr, S, Serr
                H_q68_plot, H_q95_plot = H_q68, H_q95

            out[k]["H"] = dict(value=H_plot, err=Herr_plot, mock68=H_q68_plot, mock95=H_q95_plot)
            out[k]["A"] = dict(value=A, err=Aerr, mock68=A_q68, mock95=A_q95)
            out[k]["S"] = dict(value=S_plot, err=Serr_plot, mock68=np.nan, mock95=np.nan)
        except Exception as exc:
            print(f"[warn] projected full-range totals failed for {key}: {exc!r}")
    return out


def _global_total_marker_values(best: dict, *, panel: str, angle: bool) -> tuple[float, float, float]:
    """Return (observed, mock68, mock95) in the plotting units of an extrinsic panel."""
    panel = str(panel).lower()
    if panel in {"h", "dipole", "h_ext"}:
        y_obs = _safe_float_from_mapping(best, "H_ext", _safe_float_from_mapping(best, "A_dip", np.nan))
        y68 = _first_finite_mapping_value(best, ["lookelsewhere_H_q1sigma", "null_max_abs_H_ext_q1sigma", "lookelsewhere_H_q68", "null_max_abs_H_ext_q68"])
        y95 = _first_finite_mapping_value(best, ["lookelsewhere_H_q2sigma", "null_max_abs_H_ext_q2sigma", "lookelsewhere_H_q95", "null_max_abs_H_ext_q95"])
        if angle:
            y_obs = _scalar_asin_deg(y_obs)
            y68 = _scalar_asin_deg(y68)
            y95 = _scalar_asin_deg(y95)
        return float(y_obs), float(y68), float(y95)
    if panel in {"sign", "axial_sign", "sign_asym"}:
        y_obs = _safe_float_from_mapping(best, "sign_asym_ext_percent", np.nan)
        y68 = _first_finite_mapping_value(best, ["lookelsewhere_sign_percent_q1sigma", "null_max_abs_sign_asym_ext_percent_q1sigma", "lookelsewhere_sign_percent_q68", "null_max_abs_sign_asym_ext_percent_q68"])
        y95 = _first_finite_mapping_value(best, ["lookelsewhere_sign_percent_q2sigma", "null_max_abs_sign_asym_ext_percent_q2sigma", "lookelsewhere_sign_percent_q95", "null_max_abs_sign_asym_ext_percent_q95"])
        return float(y_obs), float(y68), float(y95)
    raise ValueError(f"Unknown extrinsic total-marker panel: {panel!r}")


def _add_left_total_marker(ax, key: str, y: float, *, size: float = 12.0) -> None:
    """Draw one filled left-edge triangle for a full-range/unbinned value."""
    if not np.isfinite(y):
        return
    color = STYLE.get(str(key).lower(), {"line": "black"}).get("line", "black")
    k = str(key).lower()
    # Keep both catalog markers visually attached to the left frame; use only a
    # small offset to avoid exact overlap.
    # Catalogue markers sit just inside the left frame.  The Carrón marker is
    # nudged further right, while Chen is nudged slightly left, so both remain
    # readable without being detached from the frame.
    x = 0.018 if k in {"carron", "chen"} else 0.018
    ax.plot(
        [x], [y], marker=">", linestyle="none", transform=ax.get_yaxis_transform(),
        markersize=size, markeredgewidth=1.15, markeredgecolor=color,
        markerfacecolor=color, fillstyle="full", clip_on=False, zorder=30,
    )


def _add_global_total_markers(ax, best: dict, key: str, *, panel: str, angle: bool) -> None:
    """Draw only the full-range measurement marker on extrinsic panels.

    The previous version also drew mock 68/95 reference triangles.  Those are now
    moved to the compact value legend to keep the panel visually unambiguous.
    """
    y_obs, _y68, _y95 = _global_total_marker_values(best, panel=panel, angle=angle)
    _add_left_total_marker(ax, key, y_obs, size=12.0)


def _fmt_val_err_mock(v: float, e: float, m68: float, m95: float, *, nd: int = 2) -> str:
    """Compact value±err [mock 1σ/2σ] formatter."""
    if not np.isfinite(v):
        return "—"
    if np.isfinite(e):
        base = f"{v:.{nd}f}±{e:.{nd}f}"
    else:
        base = f"{v:.{nd}f}"
    if np.isfinite(m68) or np.isfinite(m95):
        a = f"{m68:.{nd}f}" if np.isfinite(m68) else "—"
        b = f"{m95:.{nd}f}" if np.isfinite(m95) else "—"
        return f"{base} [{a}/{b}]"
    return base


def _format_fullrange_values_legend(
    projected_totals: dict[str, dict[str, dict[str, float]]],
    datasets: list[tuple[str, str, pd.DataFrame, dict]],
    *,
    angle: bool,
) -> str:
    """Legend text with unbinned values, 1σ errors and mock 1σ/2σ levels."""
    bycat = {str(k).lower(): (label, best) for k, label, _zext, best in datasets}
    rows = ["Full-range values: value±1σ [mock 1σ/2σ]"]
    rowdefs = [
        ("H", "H", 2),
        ("A", "CCW/CW", 2),
        ("S", "S", 2),
        ("D", "Dip.", 2),
        ("X", "Axial", 2),
    ]
    for code, name, nd in rowdefs:
        parts = []
        for key in ["carron", "chen"]:
            tag = _sigma_label_from_catalog_key(key)
            if code in {"H", "A", "S"}:
                info = projected_totals.get(key, {}).get(code, {})
                txt = _fmt_val_err_mock(
                    _safe_float_from_mapping(info, "value"),
                    _safe_float_from_mapping(info, "err"),
                    _safe_float_from_mapping(info, "mock68"),
                    _safe_float_from_mapping(info, "mock95"),
                    nd=nd,
                )
            else:
                label_best = bycat.get(key)
                if label_best is None:
                    txt = "—"
                else:
                    _label, best = label_best
                    if code == "D":
                        v, m68, m95 = _global_total_marker_values(best, panel="H", angle=angle)
                        raw_v = _safe_float_from_mapping(best, "H_ext", _safe_float_from_mapping(best, "A_dip", np.nan))
                        raw_e = _safe_float_from_mapping(best, "H_ext_err", np.nan)
                        e = _scalar_asin_err_deg(raw_v, raw_e) if angle else raw_e
                    else:
                        v, m68, m95 = _global_total_marker_values(best, panel="sign", angle=False)
                        e = _safe_float_from_mapping(best, "sign_asym_ext_percent_err", np.nan)
                    txt = _fmt_val_err_mock(v, e, m68, m95, nd=nd)
            parts.append(f"{tag}: {txt}")
        rows.append(f"{name}: " + "; ".join(parts))
    return "\n".join(rows)

def _apply_paper_angle_panel_limits(*, angle: bool, ax_pH, ax_eH,
                                   ax_pA=None, ax_eA=None, ax_pS=None,
                                   upper_limits: dict | None = None) -> None:
    """Retain automatic lower bounds; apply requested angular-panel upper bounds.

    Only the requested upper endpoints change. If future data exceed a
    requested upper bound, expand it rather than clipping an observed result.
    The dimensionless panels keep their previous autoscaling.
    """
    axes = {"H_proj": ax_pH, "A_dip": ax_eH, "A_sign": ax_pA, "A_ax": ax_eA, "S_proj": ax_pS}
    targets = {"H_proj": ANGLE_PANEL_HANDEDNESS_YMAX_DEG,
               "A_dip": ANGLE_PANEL_DIPOLE_YMAX_DEG,
               "A_sign": ANGLE_PANEL_SIGN_YMAX_PERCENT,
               "A_ax": ANGLE_PANEL_AXIAL_SIGN_YMAX_PERCENT, "S_proj": 15.4}
    if upper_limits is not None:
        if set(upper_limits)-set(targets):
            raise ValueError("Unknown angular panel upper-limit key")
        targets.update(upper_limits)
    for key, ax in axes.items():
        if ax is None:
            continue
        ax.autoscale(enable=True, axis="y")
        ax.margins(y=0.10)
        if angle and key in targets:
            low, auto_high = ax.get_ylim()
            requested = float(targets[key])
            if not np.isfinite(requested) or requested <= low:
                raise ValueError(f"Invalid upper bound for {key}: {requested}")
            # Never truncate data, error envelopes, or the null reference lines.
            data_high = float(ax.dataLim.ymax)
            high = auto_high if data_high >= requested else requested
            ax.set_ylim(low, high)


def _draw_kde_handedness_contours_on_current_mollweide(boot_i: pd.DataFrame, best_ref: dict, color: str, *,
                                                       axis_display_mode: str, smooth_fwhm_deg: float) -> bool:
    """Draw vector KDE HPD contours for handedness-axis bootstrap best fits.

    The bootstrap CSV stores the best axis from the continuous handedness dipole
    scan.  This helper uses the tangent-plane KDE contour machinery, whose
    output is drawn with ``hp.projplot`` line segments and is therefore vectorial
    in PDF.
    """
    if boot_i is None or len(boot_i) < 5 or not {"ra_deg", "dec_deg"}.issubset(boot_i.columns):
        return False
    try:
        ref_ra = float(best_ref.get("ra_deg", np.nan))
        ref_dec = float(best_ref.get("dec_deg", np.nan))
        X, Y, Z, ra0, dec0, thresholds, _summary, _boot_disp = _kde_density_and_hpd(
            boot_i,
            best={"ra_deg": ref_ra, "dec_deg": ref_dec},
            axis_display_mode=axis_display_mode,
            kde_bw_scale=1.0,
            area_nside=128,
            grid_size=280,
            grid_pad_deg=10.0,
        )
        _draw_kde_contours_on_healpy(X=X, Y=Y, Z=Z, thresholds=thresholds, ra0=ra0, dec0=dec0, color=color)
        return True
    except Exception as exc:
        print(f"[warn] vector handedness-axis KDE contours failed: {exc!r}")
        return False


