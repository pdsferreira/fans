def add_zbin_lookelsewhere_pvalues(zstats: pd.DataFrame, null_df: pd.DataFrame) -> pd.DataFrame:
    """Append per-bin look-elsewhere p-values from a null dataframe."""
    if zstats is None or len(zstats) == 0 or null_df is None or len(null_df) == 0:
        return zstats
    out = zstats.copy()
    for idx, row in out.iterrows():
        try:
            ib = int(row["zbin_id"])
        except Exception:
            continue
        hcol = f"H_ext_zbin_{ib}"
        scol = f"sign_asym_ext_percent_zbin_{ib}"
        if hcol in null_df.columns and "H_ext" in out.columns:
            nv = np.abs(pd.to_numeric(null_df[hcol], errors="coerce").to_numpy(float))
            nv = nv[np.isfinite(nv)]
            obs = abs(float(row["H_ext"])) if np.isfinite(row["H_ext"]) else np.nan
            if len(nv) and np.isfinite(obs):
                p = (1.0 + np.count_nonzero(nv >= obs)) / (len(nv) + 1.0)
                out.loc[idx, "p_global_lookelsewhere"] = p
                out.loc[idx, "z_global_lookelsewhere_one_sided_equiv"] = _normal_one_sided_z_from_p(p)
                out.loc[idx, "z_global_lookelsewhere_two_sided_equiv"] = _normal_two_sided_z_from_p(p)
        if scol in null_df.columns and "sign_asym_ext_percent" in out.columns:
            sv = np.abs(pd.to_numeric(null_df[scol], errors="coerce").to_numpy(float))
            sv = sv[np.isfinite(sv)]
            obs_s = abs(float(row["sign_asym_ext_percent"])) if np.isfinite(row["sign_asym_ext_percent"]) else np.nan
            if len(sv) and np.isfinite(obs_s):
                ps = (1.0 + np.count_nonzero(sv >= obs_s)) / (len(sv) + 1.0)
                out.loc[idx, "p_sign_asym_global_lookelsewhere"] = ps
                out.loc[idx, "z_sign_asym_global_lookelsewhere_one_sided_equiv"] = _normal_one_sided_z_from_p(ps)
                out.loc[idx, "z_sign_asym_global_lookelsewhere_two_sided_equiv"] = _normal_two_sided_z_from_p(ps)
    return out


def apply_spatial_bootstrap_errors(boot: pd.DataFrame, best: dict, zstats: pd.DataFrame,
                                   *, outdir: Path, key: str) -> tuple[dict,pd.DataFrame]:
    """Populate published error columns from actual paired bootstrap realizations."""
    from spirality.resampling import bootstrap_summary, covariance_complete
    best=dict(best); zstats=zstats.copy()
    names=["A_dip","H0_dip","sign_asym_ext_percent","sign_asym_ext_residual_percent"]
    for stat in names:
        if stat in boot:
            for k,v in bootstrap_summary(pd.to_numeric(boot[stat],errors="coerce")).items():
                best[f"{stat}_{k}"]=v
        for ridx,row in zstats.iterrows():
            col=f"{stat}_zbin_{int(row.zbin_id)}"
            if col in boot:
                for k,v in bootstrap_summary(pd.to_numeric(boot[col],errors="coerce")).items():
                    zstats.loc[ridx,f"{stat}_{k}"]=v
            conditional=f"conditional_{col}"
            if conditional in boot:
                zstats.loc[ridx,f"{stat}_conditional_axis_err"]=bootstrap_summary(boot[conditional])["err"]
    best["H_ext_err"]=best.get("A_dip_err",np.nan)
    best["error_model"]="spatial_block_bootstrap_reselected_global_axis"
    best["H_ext_sigma"]=best["H_ext_err"]
    if "A_dip_err" in zstats: zstats["H_ext_err"]=zstats.A_dip_err
    zstats["error_model"]="spatial_block_bootstrap_reselected_global_axis"
    # Transform bootstrap draws, not a clipped best value plus derivative error.
    for ridx,row in zstats.iterrows():
        col=f"A_dip_zbin_{int(row.zbin_id)}"
        if col in boot:
            vals=pd.to_numeric(boot[col],errors="coerce").to_numpy(float)
            angle=np.full(len(vals),np.nan); good=np.isfinite(vals)&(np.abs(vals)<=1)
            angle[good]=np.rad2deg(np.arcsin(vals[good]))
            zstats.loc[ridx,"H_ext_angle_err_deg"]=bootstrap_summary(angle)["err"]
    covariance_index=[]
    for prefix in ["","conditional_"]:
        cols=[f"{prefix}{stat}_zbin_{int(ib)}" for stat in names for ib in zstats.zbin_id if f"{prefix}{stat}_zbin_{int(ib)}" in boot]
        if cols:
            cov,n=covariance_complete(boot[cols].to_numpy(float))
            np.save(outdir/f"{key}_extrinsic_{prefix}bootstrap_covariance.npy",cov)
            for i,col in enumerate(cols): covariance_index.append({"kind":prefix or "reselected_global_axis","column_id":i,"quantity":col,"n_complete_draws":n})
    pd.DataFrame(covariance_index).to_csv(outdir/f"{key}_extrinsic_bootstrap_covariance_index.csv",index=False)
    # Empirical axial distances; not the ad-hoc atan(sigma_A/A) surrogate.
    if {"ra_deg","dec_deg"}.issubset(boot):
        xyz=unit_xyz_from_radec(boot.ra_deg.to_numpy(float),boot.dec_deg.to_numpy(float))
        theta=np.rad2deg(np.arccos(np.clip(np.abs(xyz@_axis_vector_from_best(best)),0,1)))
        good=theta[np.isfinite(theta)]
        if len(good):
            best["axis_bootstrap_radius_68_deg"]=float(np.percentile(good,68.2689492137))
            best["axis_bootstrap_radius_95_deg"]=float(np.percentile(good,95))
    return best,zstats

def run_catalog_extrinsic(
    *,
    key: str,
    label: str,
    arm_path: Path,
    outdir: Path,
    zbin_edges: np.ndarray,
    nside_scan: int,
    nside_bootstrap: int,
    bootstrap_B: int,
    seed: int,
    weight_mode: str,
    chunk_size: int,
    no_bootstrap: bool,
    axis_display_mode: str,
    reuse_existing_extrinsic: bool = False,
    axis_contour_nside: int = 64,
    axis_contour_smooth_fwhm_deg: float = 8.0,
    extrinsic_null_B: int = 0,
    extrinsic_null_modes: list[str] | tuple[str, ...] = ("block",),
    extrinsic_null_block_nside: int = 16,
    axis_objective: str = "dipole",
    zbin_axis_mode: str = "fixed_global",
) -> tuple[pd.DataFrame, dict, pd.DataFrame, pd.DataFrame]:
    zstats_path = outdir / f"{key}_extrinsic_zbins.csv"
    boot_path = outdir / f"{key}_extrinsic_bootstrap_bestfits.csv"
    summ_path = outdir / f"{key}_extrinsic_bootstrap_summary.csv"
    scan_path = outdir / f"{key}_extrinsic_direction_scan.csv"
    best_path = outdir / f"{key}_extrinsic_bestfit.csv"

    from spirality.provenance import file_digest, code_fingerprint
    import json
    method_signature = {"analysis_schema": "88.1", "arm_sha256": file_digest(arm_path),
                        "source_sha256": code_fingerprint(Path(__file__).resolve().parents[1]),
                        "parent_sha256": file_digest(arm_path.parent / "node_spirality.csv") if (arm_path.parent / "node_spirality.csv").exists() else None,
                        "nside_scan": nside_scan, "nside_bootstrap": nside_bootstrap,
                        "bootstrap_B": bootstrap_B, "no_bootstrap": no_bootstrap,
                        "extrinsic_null_B": extrinsic_null_B, "null_modes": list(extrinsic_null_modes),
                        "null_nside": extrinsic_null_block_nside, "seed": seed,
                        "weight_mode": weight_mode, "axis_objective": axis_objective,
                        "zbin_axis_mode": zbin_axis_mode, "edges": list(map(float,zbin_edges))}
    signature_path = outdir / f"{key}_extrinsic_completed_signature.json"
    if reuse_existing_extrinsic:
        if not signature_path.exists() or json.loads(signature_path.read_text()) != method_signature:
            raise ValueError("Refusing to reuse stale/incomplete extrinsic products. Recompute without --reuse-existing-extrinsic.")
        for path in [scan_path, best_path, zstats_path]:
            if not path.exists(): raise FileNotFoundError(path)
        return (pd.read_csv(zstats_path), pd.read_csv(best_path).iloc[0].to_dict(),
                pd.read_csv(boot_path) if boot_path.exists() else pd.DataFrame(), pd.read_csv(scan_path))

    # A failed recomputation must not leave an old completion marker reusable.
    if signature_path.exists(): signature_path.unlink()
    d = read_arm_table(arm_path)
    from spirality.selection import effective_redshift, redshift_bin_ids
    zin = redshift_bin_ids(effective_redshift(d), zbin_edges) >= 0
    d = d.loc[zin].reset_index(drop=True)
    if len(d) == 0:
        raise ValueError("No accepted arms in the requested extrinsic redshift range")
    xyz = unit_xyz_from_radec(d["ra"].to_numpy(float), d["dec"].to_numpy(float))
    weights = arm_weights(d, weight_mode)
    dirs = healpix_direction_grid(nside_scan)

    print(f"[catalog:{key}] arms={len(d):,}; scan directions={len(dirs):,}; nside={nside_scan}")
    scan = scan_axis_grid(arm_xyz=xyz, sphi=d["S_tangential"].to_numpy(float), directions=dirs, weights=weights, chunk_size=chunk_size, progress=True)
    best = best_axis_from_scan(scan, objective=axis_objective)
    best["catalog_key"] = key
    best["catalog_label"] = label
    best["n_arms"] = int(len(d))
    best["weight_mode"] = weight_mode
    best["axis_objective"] = str(axis_objective)
    best["zbin_axis_mode"] = str(zbin_axis_mode)
    ra_disp, dec_disp = canonicalize_axis_radec(
        best["ra_deg"], best["dec_deg"], mode=axis_display_mode,
        ref_ra_deg=float(best["ra_deg"]), ref_dec_deg=float(best["dec_deg"])
    )
    best["ra_deg_display"] = float(ra_disp)
    best["dec_deg_display"] = float(dec_disp)
    best["axis_display_mode"] = str(axis_display_mode)
    # Point estimates first; actual spatial bootstrap errors are assigned below.
    # Analytic sign-noise scales are retained as diagnostics only.
    try:
        full_stats = _stats_for_fixed_axis_subset(xyz, d["S_tangential"].to_numpy(float), weights, best)
        for _k, _v in full_stats.items():
            if _k not in best or not np.isfinite(_safe_float_from_mapping(best, _k)):
                best[_k] = _v
        best["axis_angular_sigma_deg_dipole"] = float(np.rad2deg(np.arctan2(
            abs(best.get("H_ext_err", np.nan)), max(abs(best.get("H_ext", np.nan)), 1e-15)
        ))) if np.isfinite(best.get("H_ext", np.nan)) and np.isfinite(best.get("H_ext_err", np.nan)) else np.nan
        best["axis_angular_95_deg_dipole"] = float(min(90.0, 2.0 * best["axis_angular_sigma_deg_dipole"])) if np.isfinite(best.get("axis_angular_sigma_deg_dipole", np.nan)) else np.nan
    except Exception as exc:
        print(f"[warn] could not compute full-sample fixed-axis errors for {key}: {exc!r}")

    outdir.mkdir(parents=True, exist_ok=True)
    scan.to_csv(scan_path, index=False)
    pd.DataFrame([best]).to_csv(best_path, index=False)
    print(f"[write] {scan_path}")
    print(f"[write] {best_path}")

    if int(extrinsic_null_B) > 0:
        requested_modes = list(extrinsic_null_modes)
        if any(str(m).lower() == "all" for m in requested_modes):
            requested_modes = ["arm", "node", "block"]
        all_summaries = []
        all_zbin_summaries = []
        for imode, mode in enumerate(requested_modes):
            mode = str(mode).lower()
            group_codes, n_groups, group_desc = make_extrinsic_null_groups(
                d=d, arm_xyz=xyz, mode=mode, block_nside=int(extrinsic_null_block_nside)
            )
            null_df, null_summary = extrinsic_signflip_lookelsewhere_null(
                arm_xyz=xyz,
                sphi=d["S_tangential"].to_numpy(float),
                directions=dirs,
                weights=weights,
                best=best,
                B=int(extrinsic_null_B),
                seed=seed + 200000 + 1000 * imode,
                chunk_size=chunk_size,
                group_codes=group_codes,
                null_mode=mode,
                block_nside=int(extrinsic_null_block_nside) if mode == "block" else None,
                group_description=group_desc,
                z_eff=d["z_eff"].to_numpy(float),
                zbin_edges=zbin_edges,
                axis_objective=axis_objective,
                zbin_axis_mode=zbin_axis_mode,
            )
            null_path = outdir / f"{key}_extrinsic_lookelsewhere_signflip_{mode}_null.csv"
            summ_path_mode = outdir / f"{key}_extrinsic_lookelsewhere_signflip_{mode}_summary.csv"
            zbin_null_summary = summarize_lookelsewhere_null_zbins(
                null_df, zbin_edges, null_mode=mode,
                block_nside=int(extrinsic_null_block_nside) if mode == "block" else None,
            )
            zbin_summ_path = outdir / f"{key}_extrinsic_lookelsewhere_signflip_{mode}_zbin_summary.csv"
            null_df.to_csv(null_path, index=False)
            null_summary.to_csv(summ_path_mode, index=False)
            zbin_null_summary.to_csv(zbin_summ_path, index=False)
            print(f"[write] {null_path}")
            print(f"[write] {summ_path_mode}")
            print(f"[write] {zbin_summ_path}")
            all_summaries.append(null_summary)
            all_zbin_summaries.append(zbin_null_summary)
            if mode == "arm":
                null_df.to_csv(outdir / f"{key}_extrinsic_lookelsewhere_signflip_null.csv", index=False)
                null_summary.to_csv(outdir / f"{key}_extrinsic_lookelsewhere_signflip_summary.csv", index=False)
        if all_summaries:
            all_summary = pd.concat(all_summaries, ignore_index=True)
            all_summary.to_csv(outdir / f"{key}_extrinsic_lookelsewhere_signflip_allmodes_summary.csv", index=False)
            print(f"[write] {outdir / f'{key}_extrinsic_lookelsewhere_signflip_allmodes_summary.csv'}")
            for col, outkey in [
                ("null_max_abs_H_ext_q1sigma", "lookelsewhere_H_q1sigma"),
                ("null_max_abs_H_ext_q2sigma", "lookelsewhere_H_q2sigma"),
                ("null_max_abs_H_ext_q68", "lookelsewhere_H_q68"),
                ("null_max_abs_H_ext_q95", "lookelsewhere_H_q95"),
                ("null_selected_axis_sign_percent_q1sigma", "lookelsewhere_sign_percent_q1sigma"),
                ("null_selected_axis_sign_percent_q2sigma", "lookelsewhere_sign_percent_q2sigma"),
                ("null_selected_axis_sign_percent_q68", "lookelsewhere_sign_percent_q68"),
                ("null_selected_axis_sign_percent_q95", "lookelsewhere_sign_percent_q95"),
            ]:
                if col in all_summary.columns:
                    vals = pd.to_numeric(all_summary[col], errors="coerce").to_numpy(float)
                    best[outkey] = float(np.nanmax(vals)) if np.any(np.isfinite(vals)) else np.nan
            if "p_global_lookelsewhere" in all_summary.columns:
                src_rows = all_summary[all_summary["null_mode"].isin(requested_modes)] if "null_mode" in all_summary.columns else all_summary
                best["p_global_lookelsewhere"] = float(np.nanmin(pd.to_numeric(src_rows["p_global_lookelsewhere"], errors="coerce")))
                best["z_global_lookelsewhere_one_sided_equiv"] = _normal_one_sided_z_from_p(best["p_global_lookelsewhere"])
                best["z_global_lookelsewhere_two_sided_equiv"] = _normal_two_sided_z_from_p(best["p_global_lookelsewhere"])
                if "p_sign_asym_global_lookelsewhere" in src_rows.columns:
                    psg = float(np.nanmin(pd.to_numeric(src_rows["p_sign_asym_global_lookelsewhere"], errors="coerce")))
                    if np.isfinite(psg):
                        best["p_sign_asym_global_lookelsewhere"] = psg
                        best["z_sign_asym_global_lookelsewhere_one_sided_equiv"] = _normal_one_sided_z_from_p(psg)
                        best["z_sign_asym_global_lookelsewhere_two_sided_equiv"] = _normal_two_sided_z_from_p(psg)
            best["lookelsewhere_null_modes"] = ",".join(map(str, requested_modes))
            pd.DataFrame([best]).to_csv(best_path, index=False)
        if all_zbin_summaries:
            all_zbin_summary = pd.concat(all_zbin_summaries, ignore_index=True)
            all_zbin_summary.to_csv(outdir / f"{key}_extrinsic_lookelsewhere_signflip_allmodes_zbin_summary.csv", index=False)
            print(f"[write] {outdir / f'{key}_extrinsic_lookelsewhere_signflip_allmodes_zbin_summary.csv'}")
    
    plot_healpix_h_map(scan, nside=nside_scan, out=outdir / f"{key}_extrinsic_H_map.pdf", title=f"{label}: extrinsic H scan", best=best)

