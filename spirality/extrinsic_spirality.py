def bootstrap_axes(
    *, d: pd.DataFrame, directions: pd.DataFrame, nside_block: int, B: int, seed: int,
    weight_mode: str, chunk_size: int, axis_objective: str = "dipole",
    fixed_axis: dict | None = None, edges: np.ndarray | None = None,
    block_ids: np.ndarray | None = None,
) -> pd.DataFrame:
    """Shared spatial block draws; refit H0, rescan axis, recompute each statistic.

    Main binned bootstrap repeats the entire fixed-GLOBAL-axis pipeline (a new
    global axis per resample, not a separate search per bin). Conditional values
    on the observed global axis are saved separately. Count-only statistics
    count repeated arms once per bootstrap replication, not once per unique arm.
    """
    from spirality.resampling import healpix_blocks, block_draw_counts
    from spirality.selection import redshift_bin_ids
    xyz=unit_xyz_from_radec(d.ra.to_numpy(float),d.dec.to_numpy(float))
    h=d.S_tangential.to_numpy(float); base_w=arm_weights(d,weight_mode)
    ids=healpix_blocks(d.ra.to_numpy(float),d.dec.to_numpy(float),nside_block) if block_ids is None else np.asarray(block_ids)
    unique,inv,counts=block_draw_counts(ids,B,seed)
    if len(unique)<2: raise ValueError("At least two spatial blocks are needed for extrinsic bootstrap")
    bins=redshift_bin_ids(d.z_eff.to_numpy(float),edges) if edges is not None else None
    rows=[]
    for b,c in enumerate(counts):
        if b%10==0: print(f"[bootstrap] {b+1}/{B}",flush=True)
        cw=c[inv].astype(float); w=base_w*cw
        try:
            scan=scan_axis_grid(arm_xyz=xyz,sphi=h,directions=directions,weights=w,count_weights=cw,chunk_size=chunk_size,progress=False)
            best=best_axis_from_scan(scan,objective=axis_objective)
        except ValueError:
            rows.append({"bootstrap_id":b,"bootstrap_valid":False}); continue
        best.update(_stats_for_fixed_axis_subset(xyz,h,w,best,count_weights=cw))
        best["bootstrap_id"]=b; best["bootstrap_valid"]=True
        if fixed_axis is not None:
            cond=_stats_for_fixed_axis_subset(xyz,h,w,fixed_axis,count_weights=cw)
            for key in ["A_dip","H0_dip","sign_asym_ext_percent","sign_asym_ext_residual_percent"]:
                best[f"conditional_{key}"]=cond[key]
        if bins is not None:
            for ib in range(len(edges)-1):
                m=(bins==ib)&(cw>0)
                for prefix,axis in [("",best),("conditional_",fixed_axis if fixed_axis is not None else best)]:
                    st=_stats_for_fixed_axis_subset(xyz[m],h[m],w[m],axis,count_weights=cw[m])
                    for key in ["A_dip","H0_dip","sign_asym_ext_percent","sign_asym_ext_residual_percent"]:
                        best[f"{prefix}{key}_zbin_{ib}"]=st[key]
        rows.append(best)
    return pd.DataFrame(rows)


def canonicalize_axis_radec(
    ra_deg: np.ndarray | float,
    dec_deg: np.ndarray | float,
    *,
    mode: str = "nearest_best",
    ref_ra_deg: float | None = None,
    ref_dec_deg: float | None = None,
) -> tuple[np.ndarray, np.ndarray]:
    """Canonicalize axial directions for display/statistics.

    For an axial direction, d and -d are the same physical axis.  The robust
    default is mode='nearest_best': for each bootstrap axis, choose the sign
    (axis or antipode) that is closest to a reference direction, normally the
    best-fit axis.  This flips only the points that need flipping and avoids
    artificially splitting one cluster into two antipodal clusters.

    mode='ra_ge_180' is kept as a diagnostic hard-RA convention.
    mode='none' leaves directions unchanged and should not be used for final
    axial error estimates.
    """
    ra = np.asarray(ra_deg, dtype=float).copy()
    dec = np.asarray(dec_deg, dtype=float).copy()
    scalar = ra.ndim == 0
    ra = np.atleast_1d(ra)
    dec = np.atleast_1d(dec)
    ra = ra % 360.0

    if mode == "none":
        pass
    elif mode == "ra_ge_180":
        m = ra < 180.0
        ra[m] = (ra[m] + 180.0) % 360.0
        dec[m] = -dec[m]
    elif mode in {"nearest_best", "nearest_ref", "bestfit"}:
        if ref_ra_deg is None or ref_dec_deg is None:
            # Backward-compatible fallback for legacy calls without a reference.
            m = ra < 180.0
            ra[m] = (ra[m] + 180.0) % 360.0
            dec[m] = -dec[m]
        else:
            v = unit_xyz_from_radec(ra, dec)
            ref = unit_xyz_from_radec(np.array([float(ref_ra_deg)]), np.array([float(ref_dec_deg)]))[0]
            m = (v @ ref) < 0.0
            ra[m] = (ra[m] + 180.0) % 360.0
            dec[m] = -dec[m]
    else:
        raise ValueError(f"Unknown axis display mode: {mode}")

    if scalar:
        return np.array(ra[0]), np.array(dec[0])
    return ra, dec


def unwrap_ra_about(ra_deg: np.ndarray, center_deg: float) -> np.ndarray:
    return float(center_deg) + ((np.asarray(ra_deg, dtype=float) - float(center_deg) + 180.0) % 360.0 - 180.0)


def q16_q50_q84(arr: np.ndarray) -> tuple[float, float, float]:
    q16, q50, q84 = np.nanpercentile(np.asarray(arr, dtype=float), [16, 50, 84])
    return float(q16), float(q50), float(q84)


def update_best_with_bootstrap_summary(
    boot: pd.DataFrame,
    best: dict,
    *,
    axis_display_mode: str,
) -> tuple[pd.DataFrame, dict]:
    """Summarize bootstrap axes with axial/RA-wrap handling.

    The returned best dict gains display-coordinate fields and uncertainty
    fields used by panel labels and contour maps.
    """
    best = dict(best)
    best_ra_disp_arr, best_dec_disp_arr = canonicalize_axis_radec(
        float(best["ra_deg"]), float(best["dec_deg"]), mode=axis_display_mode,
        ref_ra_deg=float(best["ra_deg"]), ref_dec_deg=float(best["dec_deg"])
    )
    best_ra_disp = float(best_ra_disp_arr)
    best_dec_disp = float(best_dec_disp_arr)
    best["ra_deg_display"] = best_ra_disp
    best["dec_deg_display"] = best_dec_disp
    best["axis_display_mode"] = str(axis_display_mode)

    if len(boot) == 0:
        return pd.DataFrame(), best

    ra_boot, dec_boot = canonicalize_axis_radec(
        boot["ra_deg"].to_numpy(float),
        boot["dec_deg"].to_numpy(float),
        mode=axis_display_mode,
        ref_ra_deg=float(best["ra_deg"]), ref_dec_deg=float(best["dec_deg"]),
    )
    ra_unwrapped = unwrap_ra_about(ra_boot, best_ra_disp)

    ra_q16, ra_q50, ra_q84 = q16_q50_q84(ra_unwrapped)
    dec_q16, dec_q50, dec_q84 = q16_q50_q84(dec_boot)
    h_q16, h_q50, h_q84 = q16_q50_q84(boot["H_ext"].to_numpy(float))
    s_q16, s_q50, s_q84 = q16_q50_q84(boot["sign_asym_ext_percent"].to_numpy(float))

    h_best = float(best["H_ext"])
    h_sigma = 0.5 * (h_q84 - h_q16)
    h_z = h_best / h_sigma if np.isfinite(h_sigma) and h_sigma > 0 else np.nan

    # Errors are quoted around the best-fit display direction/value.  RA is first
    # unwrapped around the best-fit display RA so RA=359 and RA=1 are treated as close.
    best.update({
        "ra_deg_median": float(ra_q50 % 360.0),
        "dec_deg_median": float(dec_q50),
        "ra_deg_q16": float(ra_q16),
        "ra_deg_q50": float(ra_q50),
        "ra_deg_q84": float(ra_q84),
        "dec_deg_q16": float(dec_q16),
        "dec_deg_q50": float(dec_q50),
        "dec_deg_q84": float(dec_q84),
        "ra_deg_err_minus": float(abs(best_ra_disp - ra_q16)),
        "ra_deg_err_plus": float(abs(ra_q84 - best_ra_disp)),
        "dec_deg_err_minus": float(abs(best_dec_disp - dec_q16)),
        "dec_deg_err_plus": float(abs(dec_q84 - best_dec_disp)),
        "H_ext_q16": float(h_q16),
        "H_ext_q50": float(h_q50),
        "H_ext_q84": float(h_q84),
        "H_ext_err_minus": float(abs(h_best - h_q16)),
        "H_ext_err_plus": float(abs(h_q84 - h_best)),
        "H_ext_sigma": float(h_sigma),
        "H_ext_zscore": float(h_z),
        "sign_asym_ext_percent_q16": float(s_q16),
        "sign_asym_ext_percent_q50": float(s_q50),
        "sign_asym_ext_percent_q84": float(s_q84),
    })

    out = {
        "axis_display_mode": str(axis_display_mode),
        "ra_deg_best": float(best["ra_deg"]),
        "dec_deg_best": float(best["dec_deg"]),
        "ra_deg_display_best": best_ra_disp,
        "dec_deg_display_best": best_dec_disp,
        "ra_deg_median": float(ra_q50 % 360.0),
        "dec_deg_median": float(dec_q50),
        "H_ext_best": h_best,
        "H_ext_zscore": float(h_z),
        "sign_asym_ext_percent_best": float(best["sign_asym_ext_percent"]),
    }
    for name, qvals in [
        ("ra_deg", (ra_q16, ra_q50, ra_q84)),
        ("dec_deg", (dec_q16, dec_q50, dec_q84)),
        ("H_ext", (h_q16, h_q50, h_q84)),
        ("sign_asym_ext_percent", (s_q16, s_q50, s_q84)),
    ]:
        q16, q50, q84 = qvals
        out[f"{name}_q16"] = float(q16)
        out[f"{name}_q50"] = float(q50)
        out[f"{name}_q84"] = float(q84)
        out[f"{name}_err_minus"] = float(q50 - q16)
        out[f"{name}_err_plus"] = float(q84 - q50)

    boot_display = boot.copy()
    boot_display["ra_deg_display"] = ra_boot
    boot_display["dec_deg_display"] = dec_boot
    boot_display["ra_deg_unwrapped_about_best"] = ra_unwrapped
    return pd.DataFrame([out]), best


def bootstrap_summary(boot: pd.DataFrame, best: dict) -> pd.DataFrame:
    """Backward-compatible bootstrap summary using the default axial convention."""
    summ, _ = update_best_with_bootstrap_summary(boot, best, axis_display_mode="ra_ge_180")
    return summ


def local_tangent_offsets(ra_deg: np.ndarray, dec_deg: np.ndarray, ra0_deg: float, dec0_deg: float) -> tuple[np.ndarray, np.ndarray]:
    dra = ((np.asarray(ra_deg) - ra0_deg + 180.0) % 360.0) - 180.0
    x = dra * np.cos(np.deg2rad(dec0_deg))
    y = np.asarray(dec_deg) - dec0_deg
    return x, y


def ellipse_lonlat(ra0: float, dec0: float, cov: np.ndarray, nsig: float, n: int = 240) -> tuple[np.ndarray, np.ndarray]:
    vals, vecs = np.linalg.eigh(cov)
    vals = np.maximum(vals, 0.0)
    t = np.linspace(0, 2*np.pi, n)
    circle = np.vstack([np.cos(t), np.sin(t)])
    xy = vecs @ (np.sqrt(vals)[:, None] * nsig * circle)
    dra = xy[0] / max(1e-6, np.cos(np.deg2rad(dec0)))
    ra = (ra0 + dra) % 360.0
    dec = np.clip(dec0 + xy[1], -90, 90)
    return ra, dec


