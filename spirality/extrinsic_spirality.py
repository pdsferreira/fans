def _nanpercentile_or_nan(values, q: float) -> float:
    vals = np.asarray(values, dtype=float)
    vals = vals[np.isfinite(vals)]
    if len(vals) == 0:
        return np.nan
    return float(np.nanpercentile(vals, float(q)))


def _first_finite_mapping_value(mapping: dict, keys: list[str] | tuple[str, ...], default=np.nan) -> float:
    for k in keys:
        try:
            v = _safe_float_from_mapping(mapping, k, np.nan)
        except Exception:
            v = np.nan
        if np.isfinite(v):
            return float(v)
    return float(default) if np.isfinite(default) else np.nan


def _add_gaussian_sigma_quantiles_from_null_df(best: dict, zstats: pd.DataFrame, null_df: pd.DataFrame) -> tuple[dict, pd.DataFrame]:
    """Add Gaussian-equivalent 1σ/2σ mock thresholds from a null dataframe.

    Keeps ``--reuse-existing-extrinsic`` useful for products made by older
    package versions that only stored q68/q95 columns.
    """
    if null_df is None or len(null_df) == 0:
        return best, zstats
    b = dict(best)
    axis_objective = str(b.get("axis_objective", "dipole")).lower()
    if axis_objective == "axial_sign":
        dip_col = "abs_A_dip_at_max_sign_asym"
        sign_col = "max_abs_sign_asym_ext_percent"
    else:
        dip_col = "max_abs_H_ext"
        sign_col = "abs_sign_asym_ext_percent_at_max_H"

    if dip_col in null_df.columns:
        vals = np.abs(pd.to_numeric(null_df[dip_col], errors="coerce").to_numpy(float))
        b["lookelsewhere_H_q1sigma"] = _nanpercentile_or_nan(vals, SIGNED_ABS_1SIGMA_PCT)
        b["lookelsewhere_H_q2sigma"] = _nanpercentile_or_nan(vals, SIGNED_ABS_2SIGMA_PCT)
    if sign_col in null_df.columns:
        vals = np.abs(pd.to_numeric(null_df[sign_col], errors="coerce").to_numpy(float))
        b["lookelsewhere_sign_percent_q1sigma"] = _nanpercentile_or_nan(vals, SIGNED_ABS_1SIGMA_PCT)
        b["lookelsewhere_sign_percent_q2sigma"] = _nanpercentile_or_nan(vals, SIGNED_ABS_2SIGMA_PCT)

    z = zstats.copy() if isinstance(zstats, pd.DataFrame) else pd.DataFrame()
    if len(z) and "zbin_id" in z.columns:
        zbin_ids = pd.to_numeric(z["zbin_id"], errors="coerce")
        for ib in sorted(set(zbin_ids.dropna().astype(int))):
            hcol = f"H_ext_zbin_{ib}"
            scol = f"sign_asym_ext_percent_zbin_{ib}"
            rowmask = pd.to_numeric(z["zbin_id"], errors="coerce").astype(float) == float(ib)
            if hcol in null_df.columns:
                hv = np.abs(pd.to_numeric(null_df[hcol], errors="coerce").to_numpy(float))
                z.loc[rowmask, "lookelsewhere_H_q1sigma"] = _nanpercentile_or_nan(hv, SIGNED_ABS_1SIGMA_PCT)
                z.loc[rowmask, "lookelsewhere_H_q2sigma"] = _nanpercentile_or_nan(hv, SIGNED_ABS_2SIGMA_PCT)
            if scol in null_df.columns:
                sv = np.abs(pd.to_numeric(null_df[scol], errors="coerce").to_numpy(float))
                z.loc[rowmask, "lookelsewhere_sign_percent_q1sigma"] = _nanpercentile_or_nan(sv, SIGNED_ABS_1SIGMA_PCT)
                z.loc[rowmask, "lookelsewhere_sign_percent_q2sigma"] = _nanpercentile_or_nan(sv, SIGNED_ABS_2SIGMA_PCT)
    return b, z


def _format_unbinned_global_sigma_lines(datasets: list[tuple[str, str, pd.DataFrame, dict]]) -> str:
    """Compact legend with full-range/unbinned mock-calibrated significances.

    The main sigma annotations in the paper panel can combine the four z bins
    using ``panel_extrinsic_sigma_combine``.  This helper separately reports
    the significance obtained from the full 0.1<z<0.6 extrinsic fit stored in
    each catalogue's ``*_extrinsic_bestfit.csv``.  This makes the distinction
    between the binned diagnostic and the single full-range fit explicit.
    """
    dip_items = []
    sign_items = []
    for key, label, _zdf, best in datasets:
        tag = _sigma_label_from_catalog_key(key, label)
        p_dip = _safe_float_from_mapping(best, "p_global_lookelsewhere")
        if np.isfinite(p_dip):
            dip_items.append(f"{tag}={_normal_one_sided_z_from_p(p_dip):.1f}")
        p_ax = _safe_float_from_mapping(best, "p_sign_asym_global_lookelsewhere")
        if np.isfinite(p_ax):
            sign_items.append(f"{tag}={_normal_one_sided_z_from_p(p_ax):.1f}")

    lines = []
    if dip_items or sign_items:
        lines.append("Unbinned/full-range σ")
    if dip_items:
        lines.append("Dipole: " + ", ".join(dip_items))
    if sign_items:
        lines.append("Axial sign: " + ", ".join(sign_items))
    return "\n".join(lines)


