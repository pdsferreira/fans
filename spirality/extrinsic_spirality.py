def _first_existing_path(paths: list[Path]) -> Path:
    for p in paths:
        if p.exists():
            return p
    return paths[0]


def _read_projected_summary(run_root: Path, key: str, weight_mode: str) -> Optional[pd.DataFrame]:
    if key == "carron":
        path = _first_existing_path([
            run_root / "carron_dr17_proxy" / "carron_proxy_ridges" / f"zbin_summary_arms_{weight_mode}.csv",
            run_root / "carron_dr16_proxy" / "carron_proxy_ridges" / f"zbin_summary_arms_{weight_mode}.csv",
        ])
        label = "Carrón et al. SDSS DR16"
    elif key == "chen":
        path = _first_existing_path([
            run_root / "chen_dr12_native_arms" / f"zbin_summary_arms_{weight_mode}.csv",
            run_root / "chen_dr12_native" / f"zbin_summary_arms_{weight_mode}.csv",
        ])
