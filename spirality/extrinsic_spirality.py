#!/usr/bin/env python3
"""
Dipolar extrinsic spirality analysis.

This module uses arm-level spirality products already generated by the main
pipeline.  It does not re-measure arms.  For each trial axis d on the sky, it
fits the dipolar projected-handedness template with an intercept,

    h_i = H0 + A_dip (n_i . d) + noise_i,

where h_i is the projected handedness of arm i and n_i is the sky position of
the parent node/arm.  The fitted extrinsic axis is the axial direction that
maximizes |A_dip|.  The intercept H0 absorbs any projected monopole, mitigating
leakage from incomplete sky coverage.  The axis is then oriented so the reported
the signed A_dip is quoted on the positive-declination representative.

Significance is assessed with grouped/block sign-flip nulls.  The full axis scan
is repeated for each null realization, so the reported p-values include the
look-elsewhere effect from searching over axes.
"""

