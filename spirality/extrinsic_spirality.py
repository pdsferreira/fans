def _normal_two_sided_z_from_p(p: float) -> float:
    try:
        from scipy.stats import norm
        p = float(np.clip(p, 1e-300, 1.0))
        return float(norm.isf(0.5 * p))
    except Exception:
        # Crude fallback; should rarely be used.
        return float("nan")


def _normal_one_sided_z_from_p(p: float) -> float:
    """One-sided Gaussian-equivalent detection significance, clipped at zero.

    For tail probabilities p > 0.5, norm.isf(p) is negative.  That is a useful
    signed deviate but not a detection significance, so for paper tables/labels
    we report max(0, Z).
    """
    try:
        from scipy.stats import norm
        p = float(np.clip(p, 1e-300, 1.0))
        return float(max(0.0, norm.isf(p)))
    except Exception:
        return float("nan")


def _factorize_groups(group_ids: np.ndarray | pd.Series | list, n: int) -> tuple[np.ndarray, int]:
    if group_ids is None:
        codes = np.arange(int(n), dtype=int)
        return codes, int(n)
    codes, uniques = pd.factorize(pd.Series(group_ids).astype(str), sort=False)
    codes = np.asarray(codes, dtype=int)
    if len(codes) != int(n):
        raise ValueError(f"group_ids length {len(codes)} != n {n}")
    # Missing groups are treated as independent arms.
    bad = codes < 0
    if np.any(bad):
        offset = int(codes.max()) + 1 if np.any(~bad) else 0
        codes[bad] = offset + np.arange(np.count_nonzero(bad))
    return codes, int(codes.max() + 1) if len(codes) else 0


def _block_group_ids_from_xyz(arm_xyz: np.ndarray, *, nside: int) -> np.ndarray:
    require_healpy()
    x = np.asarray(arm_xyz[:, 0], dtype=float)
    y = np.asarray(arm_xyz[:, 1], dtype=float)
    z = np.asarray(arm_xyz[:, 2], dtype=float)
    theta = np.arccos(np.clip(z, -1.0, 1.0))
    phi = np.mod(np.arctan2(y, x), 2.0 * np.pi)
    return hp.ang2pix(int(nside), theta, phi, nest=False)


def make_extrinsic_null_groups(
    *,
    d: pd.DataFrame,
    arm_xyz: np.ndarray,
    mode: str,
    block_nside: int,
) -> tuple[np.ndarray, int, str]:
    """Return per-arm integer group codes for grouped sign-flip nulls."""
    mode = str(mode).lower()
    n = len(d)
    if mode == "arm":
        return np.arange(n, dtype=int), n, "one independent sign flip per arm"
    if mode == "node":
        if "node_id" in d.columns:
            codes, ng = _factorize_groups(d["node_id"].to_numpy(), n)
            return codes, ng, "one common sign flip for all arms belonging to the same node_id"
        return np.arange(n, dtype=int), n, "node_id missing; fell back to one independent sign flip per arm"
    if mode == "block":
        pix = _block_group_ids_from_xyz(arm_xyz, nside=int(block_nside))
        codes, ng = _factorize_groups(pix, n)
        return codes, ng, f"one common sign flip per HEALPix block, nside={int(block_nside)}"
    raise ValueError(f"Unknown extrinsic null mode: {mode}")



def extrinsic_signflip_lookelsewhere_null(
    *,
    arm_xyz: np.ndarray,
    sphi: np.ndarray,
    directions: pd.DataFrame,
    weights: np.ndarray,
    best: dict,
    B: int,
    seed: int,
    chunk_size: int,
    group_codes: np.ndarray | None = None,
    null_mode: str = "block",
    block_nside: int | None = None,
    group_description: str = "",
    z_eff: np.ndarray | None = None,
    zbin_edges: np.ndarray | None = None,
    axis_objective: str = "dipole",
    zbin_axis_mode: str = "fixed_global",
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Grouped sign-flip null matching the chosen axis prescription.

    Each null realization performs the same look-elsewhere search used for the
    data.  If ``zbin_axis_mode='fixed_global'``, a full-sample axis is selected
    by ``axis_objective`` and every redshift bin is evaluated on that axis.  If
    ``zbin_axis_mode='per_bin_max'``, each redshift bin independently scans the
    sky and selects its own bin-specific axis using the same ``axis_objective``.

    This distinction matters for the z-bin p-values: when the data use free
    per-bin axes, the null must also re-optimize the axis in each bin, otherwise
    the look-elsewhere correction is inconsistent.
    """
    if int(B) <= 0:
        return pd.DataFrame(), pd.DataFrame()

    axis_objective = str(axis_objective).lower()
    zbin_axis_mode = str(zbin_axis_mode).lower()
    rng = np.random.default_rng(int(seed))
    sphi = np.asarray(sphi, dtype=float)
    weights = np.asarray(weights, dtype=float)
    n = len(sphi)
    if group_codes is None:
        group_codes = np.arange(n, dtype=int)
    group_codes = np.asarray(group_codes, dtype=int)
    if len(group_codes) != n:
        raise ValueError(f"group_codes length {len(group_codes)} != number of arms {n}")
    n_groups = int(group_codes.max() + 1) if len(group_codes) else 0

    obs_dip = abs(float(best.get("A_dip", best.get("H_ext", np.nan))))
    obs_sign = abs(float(best.get("sign_asym_ext_percent", np.nan)))
    avec_obs = unit_xyz_from_radec(np.array([best["ra_deg"]]), np.array([best["dec_deg"]]))[0]

    rows = []
    for b in range(int(B)):
        if b % 10 == 0:
            print(f"[extrinsic-null:{axis_objective}:{null_mode}] {b+1}/{B}", flush=True)
        group_flips = rng.choice(np.array([-1.0, 1.0]), size=n_groups, replace=True)
        flips = group_flips[group_codes]
        h_null = sphi * flips
        scan_null = scan_axis_grid(
            arm_xyz=arm_xyz, sphi=h_null, directions=directions,
            weights=weights, chunk_size=chunk_size, progress=False,
        )
        best_null_dip = best_axis_from_scan(scan_null, objective="dipole")
